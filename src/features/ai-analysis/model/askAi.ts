/** Контракт вопроса к ИИ. Сегодня — ДЕМО: ответ собирается синхронно из тех
 *  же карточек правил, без сети. Завтра функция станет async (или стримом) —
 *  интерфейс панели к этому готов: у неё уже есть состояния «думает» и
 *  «сбой», выраженные темпом глифа, а не новой поверхностью.
 *
 *  Живёт в фиче, а не в entities: entities отвечает на вопрос «что в данных»,
 *  этот модуль — «что на это отвечают». */

export interface AskContext {
  /** Имена отмеченных ★ подрядчиков, максимум два. */
  pair: string[];
  /** Готовая выжимка пары — текст карточки сценария «Сравнить подрядчиков». */
  compareText?: string;
}

/** Вопрос-подставка при пустом поле: то же поведение, что у прототипов. */
export const DEFAULT_QUESTION = 'Где выгоднее и где риски по отмеченным ★?';

/** ДЕМО-реализация. Ответ честно помечен панелью как «Ответ · демо». */
export function askAi(question: string, ctx: AskContext): string {
  if (ctx.pair.length === 2) {
    return `«${question}» — ${ctx.compareText ?? 'смотрите карточку пары выше.'}`;
  }
  const noted = ctx.pair.length ? ctx.pair.join(', ') : 'никого';
  return `«${question}» — отметьте двух подрядчиков ★ для сравнения. Сейчас отмечено: ${noted}.`;
}
