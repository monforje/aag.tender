import type { CSSProperties } from 'react';
import { cx } from '@/shared/lib/cx';
import s from './ProgressBar.module.css';

/** Тона полосы величины — закрытый состав из трёх (решение владельца
 *  25.08.2026). Тревожных тонов здесь нет намеренно: шкала отвечает
 *  «сколько», а не «хорошо ли», и красить величину в опасность значило бы
 *  выносить оценку туда, где её не делают. */
export type ProgressBarTone = 'neutral' | 'info' | 'success';

const TONE: Record<ProgressBarTone, string | undefined> = {
  neutral: undefined,
  info: s.pbarInfo,
  success: s.pbarSuccess,
};

/**
 * Полоса ВЕЛИЧИНЫ: доля одного числа в другом, показанная длиной.
 *
 * КОГДА:  вклад позиции в стоимость тендера, заполненность КП, доля запаса в
 *         лучшей цене, положение значения внутри диапазона — везде, где рядом
 *         с числом нужна его длина. ОДИН компонент на все такие места
 *         (решение владельца 25.08.2026): до него в экране сравнения жили три
 *         рукописные шкалы с разной геометрией, и одинаковые по смыслу доли
 *         выглядели разными приборами.
 * НЕ ДЛЯ: ХОДА ПРОЦЕССА — загрузка файла, обработка пачки КП (см.
 *         <Progress>): там полоса ползёт сама и обязана иметь роль
 *         `progressbar` со шкалой, а здесь она статична и описывает уже
 *         известное число. И не для микрошкалы внутри ячейки таблицы:
 *         разброс строки рисует своя `.spread-bar` — она нормируется порогом
 *         тендера, а не максимумом набора.
 *
 * UX:     ДЛИНА — ЕДИНСТВЕННЫЙ НОСИТЕЛЬ, и потому число рядом обязательно:
 *         полоса показывает соотношение, точное значение читают текстом
 *         (правило «цвет и длина не единственные каналы»). Ширина трека
 *         приходит СНАРУЖИ — классом потребителя или пропом `width`:
 *         в строке таблицы она фиксирована (96px), чтобы проценты соседних
 *         строк стояли на одной вертикали, а в панели растягивается на всю
 *         ширину. НОРМИРОВКА — ТОЖЕ СНАРУЖИ: компонент получает готовые
 *         0…100 и не знает, делили на лидера или на сотню.
 * A11Y:   `aria-hidden` — полоса ДУБЛИРУЕТ соседнее число и своего сообщения
 *         не несёт; озвучивать её значило бы прочитать одну величину дважды.
 *         Если полоса когда-нибудь останется без числа рядом, это ошибка
 *         вызова, а не повод завести здесь роль.
 *
 * @example
 * <ProgressBar value={12.4} width={96} />
 * <ProgressBar value={share} tone="info" className={s.wide} />
 */
export function ProgressBar({ value, tone = 'neutral', width, className }: {
  /** Доля 0…100. Зажимается: данные приходят из расчёта, и вылет за сотню
   *  (потенциал больше лучшей цены — бывает) не имеет права рвать вёрстку. */
  value: number;
  tone?: ProgressBarTone;
  /** Ширина трека, px. Не задана — трек тянется по месту (флекс/грид). */
  width?: number;
  className?: string;
}) {
  const clamped = Math.max(0, Math.min(100, Number.isFinite(value) ? value : 0));
  return (
    <span
      className={cx(s.pbar, TONE[tone], className)}
      style={width === undefined ? undefined : ({ width: `${width}px` } as CSSProperties)}
      aria-hidden="true"
    >
      <i className={s.pbarFill} style={{ width: `${clamped}%` }} />
    </span>
  );
}
