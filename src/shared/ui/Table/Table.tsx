import type { ReactNode } from 'react';
import { cx } from '@/shared/lib/cx';
import s from './Table.module.css';

/**
 * Модификаторы ячеек. Отдаются объектом классов, а не пропами <Td numeric>:
 * правила выравнивания сцеплены с `.table` (иначе их бьёт по специфичности
 * базовое `.table th`), а классы CSS-модуля хэшируются помодульно — класс,
 * пришедший из модуля страницы, в такой селектор не попал бы. Тот же приём,
 * что у `searchSecondaryIconClass` в <SearchTrigger>.
 *
 * - `numeric` — числа и даты вправо;
 * - `roomy`  — числовая колонка под УГЛОВУЮ отметку: штамп «МИН» в сравнении
 *               КП прибит к левому нижнему углу ячейки (≈28px + отступ 3px),
 *               и резерв делается паддингом всей колонки — он общий всем
 *               строкам, поэтому правое выравнивание не сдвигается;
 * - `mono`    — коды и артикулы моноширинным;
 * - `strong`  — колонка-якорь, с которой читают строку;
 * - `muted`   — второстепенное значение;
 * - `sub`     — <span> со второй строкой-уточнением внутри ячейки;
 * - `link`    — <a>/<Link> внутри ячейки;
 * - `rowLink` — <tr>, ведущая на страницу;
 * - `card`    — ячейка ЦЕЛИКОМ отдана своему содержимому: ни паддинга, ни
 *               фиксированной высоты шапки. Для колонки, в которой стоит не
 *               значение, а блок (карточка подрядчика в сравнении КП);
 * - `fullRow` — строка-заголовок секции: <th colSpan> на все колонки. Гасит
 *               липкость sticky-col, которая иначе застыла бы у кромки одной
 *               первой колонкой и порвала собственный colSpan;
 * - `empty`   — <td colSpan> с объяснением пустого результата.
 */
export const tableCell = {
  numeric: s.cellNumeric,
  roomy: s.cellRoomy,
  mono: s.cellMono,
  strong: s.cellStrong,
  muted: s.cellMuted,
  sub: s.cellSub,
  link: s.cellLink,
  rowLink: s.rowLink,
  card: s.cellCard,
  fullRow: s.cellFullRow,
  empty: s.empty,
} as const;

/**
 * Таблица данных: лента во всю ширину <main> с прокруткой внутри себя.
 *
 * КОГДА:  плотный список записей, который читают по колонкам — реестр,
 *         журнал, выгрузка. Внутрь кладут обычные <thead>/<tbody>.
 * НЕ ДЛЯ: раскладки (таблица — про ДАННЫЕ, а не про сетку; для сетки CSS
 *         grid); списка из одной колонки (это список, см. <TreeRow>);
 *         карточек с разнородными полями.
 *
 * UX:     первая колонка стоит в общей колонке контента — 12px от края
 *         <main>, на одной вертикали с заголовком страницы и вкладками. Ради
 *         этого блок выносится за паддинг прокрутки, разбор — в .module.css.
 *         Шапка с «тихой» заливкой (.035) СВЕТЛЕЕ ховера строки (.05), иначе
 *         подсветка под курсором читалась бы как вторая шапка; зебры нет по
 *         той же причине. Длинная таблица прокручивается ГОРИЗОНТАЛЬНО внутри
 *         своей ленты, не разъезжая страницу.
 *         caption — итог под данными (сколько показано из скольких), а не
 *         элемент полосы фильтров: он описывает таблицу, а среди контролов
 *         читался как ещё один фильтр.
 *         layout="fixed" — ширины колонок берутся ТОЛЬКО из <colgroup>, а не
 *         из содержимого. Нужно там, где колонки СРАВНИВАЮТ между собой:
 *         авторазметка меряет колонку по самому длинному значению, и у кого
 *         длиннее имя, у того шире колонка — хотя читают их как равные.
 *         Заодно это единственный режим, в котором width у <col> вообще
 *         исполняется: при авторазметке это лишь пожелание.
 *         Плата — обрезка: колонка больше не растягивается под текст, поэтому
 *         в этом режиме длинное значение уходит в многоточие (ячейкам,
 *         отданным блоку, обрезка не грозит — см. .cell--card).
 * A11Y:   настоящая <table> с <th scope="col"> — скринридер объявляет
 *         заголовок колонки при переходе по ячейкам; <caption> становится
 *         именем таблицы. Ни то ни другое не заменяется набором <div>.
 *         stickyHead не меняет разметку: шапка остаётся обычным <thead>,
 *         «липкость» — только позиционирование.
 *
 * @example
 * <Table caption={`Показано ${rows.length} из ${ROWS.length}`}>
 *   <thead><tr><th scope="col">№</th></tr></thead>
 *   <tbody>{rows.map((r) => <tr key={r.id}><td className={tableCell.mono}>{r.id}</td></tr>)}</tbody>
 * </Table>
 */
export function Table({ caption, layout, stickyHead, stickyCol, width, children }: {
  caption?: ReactNode;
  /** 'fixed' — ширины из <colgroup> (см. UX). По умолчанию авторазметка. */
  layout?: 'auto' | 'fixed';
  /**
   * Явная ширина таблицы, px. ОБЯЗАТЕЛЬНА вместе с layout="fixed" у
   * stickyHead-таблицы: у `width: max-content` вместе с table-layout:fixed
   * браузер не исполняет ширины <col> и распределяет колонки по содержимому
   * (проверено на Chrome 141). Ставится ИНЛАЙНОМ, а не наследуемой
   * CSS-переменной намеренно: переменная на обёртке грязит стиль всей
   * таблицы на каждом шаге её изменения (профилирование 24.08.2026 —
   * +130мс стиля на кадр анимации панели), инлайн-ширина на самой таблице —
   * только её раскладку. Потребитель — расчётчик ширин сравнения КП;
   * без пропа таблица sizing'ится по содержимому, как раньше.
   */
  width?: number;
  /**
   * Липкая шапка: thead прибирается к верху БЛИЖАЙШЕГО прокручиваемого
   * предка нативным position:sticky (детали — .module.css).
   *
   * КОГДА:  длинная таблица на странице со своим скроллом: строки едут под
   *         неподвижной шапкой, пока таблица не кончится, — и шапка уходит
   *         вместе с её концом.
   * НЕ ДЛЯ: коротких таблиц — прилипшая шапка ради трёх строк читается как
   *         поломка; им достаточно обычной страницы.
   *
   * Требование к окружению: между <table> и ЦЕЛЕВЫМ скроллом не должно быть
   * СВОЕГО прокручиваемого блока — его scrollport перехватил бы липкость
   * себе. Целью не обязана быть область страницы: лента сравнения КП кладёт
   * таблицу в собственный скроллблок (.band) — шапка прилипает к его кромке,
   * и это штатное использование. В режиме stickyHead обёртка отдаёт любую
   * прокрутку наружу, а декорации переезжают с обёртки на саму таблицу: та
   * теперь бывает шире обёртки. */
  stickyHead?: boolean;
  /**
   * Липкая колонка-ЯКОРЬ: первая колонка не уезжает при горизонтальной
   * прокрутке ленты.
   *
   * КОГДА:  таблица шире своей ленты И строку опознают по первой колонке —
   *         сравнение КП панорамирует на шести подрядчиках, и без якоря
   *         справа остаётся сетка чисел без единой подписи: какая это
   *         позиция, узнать неоткуда.
   * НЕ ДЛЯ: таблиц, которые целиком помещаются в ленту (липкость там ничего
   *         не держит), и таблиц, где первая колонка — не имя строки, а
   *         рядовое значение.
   *
   * Требование к разметке: первая ячейка строки должна быть заголовком
   * строки (<th scope="row">), иначе якорь виден глазом, но не существует
   * для скринридера — а это ровно та же потеря, только в другом канале.
   */
  stickyCol?: boolean;
  children: ReactNode;
}) {
  return (
    <div className={cx(s.tableWrap, stickyHead && s.tableWrapStickyHead)}>
      <table
        className={cx(
          s.table,
          layout === 'fixed' && s.tableFixed,
          stickyHead && s.tableStickyHead,
          stickyCol && s.tableStickyCol,
        )}
        style={width != null ? { width: `${width}px` } : undefined}
      >
        {caption ? <caption className={s.caption}>{caption}</caption> : null}
        {children}
      </table>
    </div>
  );
}
