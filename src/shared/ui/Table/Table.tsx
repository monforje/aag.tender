import type { ReactNode } from 'react';
import s from './Table.module.css';

/**
 * Модификаторы ячеек. Отдаются объектом классов, а не пропами <Td numeric>:
 * правила выравнивания сцеплены с `.table` (иначе их бьёт по специфичности
 * базовое `.table th`), а классы CSS-модуля хэшируются помодульно — класс,
 * пришедший из модуля страницы, в такой селектор не попал бы. Тот же приём,
 * что у `searchSecondaryIconClass` в <SearchTrigger>.
 *
 * - `numeric` — числа и даты вправо;
 * - `mono`    — коды и артикулы моноширинным;
 * - `strong`  — колонка-якорь, с которой читают строку;
 * - `muted`   — второстепенное значение;
 * - `sub`     — <span> со второй строкой-уточнением внутри ячейки;
 * - `link`    — <a>/<Link> внутри ячейки;
 * - `rowLink` — <tr>, ведущая на страницу;
 * - `card`    — ячейка ЦЕЛИКОМ отдана своему содержимому: ни паддинга, ни
 *               фиксированной высоты шапки. Для колонки, в которой стоит не
 *               значение, а блок (карточка подрядчика в сравнении КП);
 * - `empty`   — <td colSpan> с объяснением пустого результата.
 */
export const tableCell = {
  numeric: s.cellNumeric,
  mono: s.cellMono,
  strong: s.cellStrong,
  muted: s.cellMuted,
  sub: s.cellSub,
  link: s.cellLink,
  rowLink: s.rowLink,
  card: s.cellCard,
  empty: s.empty,
} as const;

/**
 * Таблица данных: лента во всю ширину <main> с прокруткой внутри себя.
 *
 * КОГДА:  плотный список записей, который читают по колонкам — реестр,
 *         журнал, выгрузка. Внутрь кладут обычные <thead>/<tbody>.
 * НЕ ДЛЯ: раскладки (таблица — про ДАННЫЕ, а не про сетку; для сетки CSS
 *         grid); списка из одной колонки (это список, см. <TreeRow>);
 *         карточек с разнородными полями.
 *
 * UX:     первая колонка стоит в общей колонке контента — 12px от края
 *         <main>, на одной вертикали с заголовком страницы и вкладками. Ради
 *         этого блок выносится за паддинг прокрутки, разбор — в .module.css.
 *         Шапка с «тихой» заливкой (.035) СВЕТЛЕЕ ховера строки (.05), иначе
 *         подсветка под курсором читалась бы как вторая шапка; зебры нет по
 *         той же причине. Длинная таблица прокручивается ГОРИЗОНТАЛЬНО внутри
 *         своей ленты, не разъезжая страницу.
 *         caption — итог под данными (сколько показано из скольких), а не
 *         элемент полосы фильтров: он описывает таблицу, а среди контролов
 *         читался как ещё один фильтр.
 * A11Y:   настоящая <table> с <th scope="col"> — скринридер объявляет
 *         заголовок колонки при переходе по ячейкам; <caption> становится
 *         именем таблицы. Ни то ни другое не заменяется набором <div>.
 *
 * @example
 * <Table caption={`Показано ${rows.length} из ${ROWS.length}`}>
 *   <thead><tr><th scope="col">№</th></tr></thead>
 *   <tbody>{rows.map((r) => <tr key={r.id}><td className={tableCell.mono}>{r.id}</td></tr>)}</tbody>
 * </Table>
 */
export function Table({ caption, children }: { caption?: ReactNode; children: ReactNode }) {
  return (
    <div className={s.tableWrap}>
      <table className={s.table}>
        {caption ? <caption className={s.caption}>{caption}</caption> : null}
        {children}
      </table>
    </div>
  );
}
