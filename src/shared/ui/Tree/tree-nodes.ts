import type { TreeRowData } from '@/shared/ui/TreeRow';

/**
 * ТАКСОНОМИЯ УЗЛОВ ДЕРЕВА — какие вообще бывают строки.
 *
 * Раньше этот список нигде не был записан и держался в голове: строки
 * собирались вызовами row({...}) с разными наборами полей, и понять, какие
 * сочетания легальны, можно было только перечитав все вызовы. Отсюда правило:
 * НОВЫЙ ВИД СТРОКИ ДОБАВЛЯЕТСЯ ЗДЕСЬ, а не подбором полей на месте.
 *
 * | Вид            | Когда брать                                   | Как выглядит                          |
 * |----------------|-----------------------------------------------|---------------------------------------|
 * | row            | Обычный пункт, ведёт на экран или витрина     | иконка + заголовок                    |
 * | row + sub      | Пункту нужно уточнение, а не второй пункт     | приписка серым 12px после заголовка   |
 * | row + count    | У пункта есть счётчик событий или количество  | розовый счётчик; muted — если это     |
 * |                |                                               | просто количество, а не уведомление   |
 * | row + avatar   | Пункт про человека или адресата               | буква-аватар; точка онлайна ТОЛЬКО    |
 * |                |                                               | если буква значит «человек в сети»    |
 * | action         | «Создать»: + Add Channel, New message         | как row с иконкой add — см. ниже      |
 * | group          | Заголовок группы строк                        | 12px tertiary, без фона и без клика   |
 * | link           | Плоский пункт со своим маршрутом              | как row, но обязательно есть path —   |
 * |                |                                               | Tree сама решает active/onClick       |
 *
 * ЧЕМ group ОТЛИЧАЕТСЯ ОТ вложенного узла — вопрос, на котором обычно и
 * ошибаются: у group НЕТ своего экрана и своей роли treeitem, это просто
 * подпись над списком. Вложенный узел (родитель + дети + линия + тоггл)
 * собирается ОТДЕЛЬНЫМ компонентом — NestedTreeNode: у него свои состояния
 * (раскрыт ли, какой ребёнок активен), которые в статических данных не
 * выразить.
 *
 * ПОЧЕМУ action ВЫДЕЛЕН, хотя рендерится как row: он ведёт не на экран, а
 * открывает создание. Сегодня разницы не видно, и это нормально — вид строки
 * описывает НАМЕРЕНИЕ, а не текущий набор пикселей. Когда действиям
 * понадобится своё оформление (а им обычно понадобится), менять придётся одно
 * место здесь, а не искать по дереву, какие из строк с иконкой add были
 * действиями.
 */
export type TreeItem =
  | ({ kind: 'row' } & TreeRowData)
  | ({ kind: 'action' } & TreeRowData)
  /** Плоский пункт со своим маршрутом. В отличие от row/action кликабелен
   *  и подсвечивается сам — Tree сверяет path с текущим адресом, а не ждёт
   *  готовый обработчик в данных. */
  | ({ kind: 'link'; path: string } & TreeRowData)
  | { kind: 'group'; title: string };

/** Строки, которые рендерятся одинаково: обычный пункт и действие. */
export function isRowLike(item: TreeItem): item is ({ kind: 'row' | 'action' } & TreeRowData) {
  return item.kind === 'row' || item.kind === 'action';
}