import { cx } from '@/shared/lib/cx';
import s from './InlineInput.module.css';

/**
 * Значение, которое правится на месте: в покое неотличимо от текста.
 *
 * КОГДА:  поле сводки, карточки, строки свойств — там, где значения в первую
 *         очередь ЧИТАЮТ, а правят изредка. Рамка у каждого такого значения
 *         превращает экран в анкету.
 * НЕ ДЛЯ: формы, которую пришли ЗАПОЛНЯТЬ: там поле обязано выглядеть полем,
 *         и рамка помогает, а не мешает (см. .search--field у <SearchInput>).
 *         Не для поиска, сужающего список (<SearchInput>), и не для даты —
 *         у неё <DatePicker>, который берёт ту же поверхность, но открывает
 *         календарь.
 *
 * UX:     поверхность общая — глобальная утилита .inline-edit (разбор в
 *         global.css, раздел 1-b): в покое ничего, заливка по наведению,
 *         белая подложка с кольцом по фокусу. Заливка растёт наружу, поэтому
 *         текст не съезжает вбок под курсором.
 *         Длинное значение обрезается многоточием, а не растягивает колонку:
 *         в сетке полей ширину назначает сетка. Целиком его видно, поставив
 *         курсор в поле.
 * A11Y:   видимой подписи у поля нет (она стоит рядом отдельным элементом),
 *         поэтому label обязателен и уходит в aria-label: соседний <dt> или
 *         <span> именем поля для скринридера не считается.
 *
 * @example
 * <InlineInput label="Ответственный" value={tender.owner} />
 */
export function InlineInput({ label, value, onChange, className }: {
  label: string;
  value: string;
  /** Не передан — поле неуправляемое: правка живёт до перезагрузки. Так и
   *  задумано, пока сохранять некуда; появится ручка — придёт onChange. */
  onChange?: (next: string) => void;
  className?: string;
}) {
  const bind = onChange
    ? { value, onChange: (e: React.ChangeEvent<HTMLInputElement>) => onChange(e.target.value) }
    : { defaultValue: value };

  return (
    <input
      className={cx('inline-edit', s.inlineInput, className)}
      aria-label={label}
      {...bind}
    />
  );
}
