import type { ReactNode } from 'react';
import s from './Page.module.css';

/**
 * Название текущего экрана в шапке страницы (14px/600).
 *
 * КОГДА:  экран верхнего уровня — то есть когда «крошить» нечего: единственный
 *         уровень и есть текущая страница.
 * НЕ ДЛЯ: дочерних экранов. Как только открыт вложенный пункт дерева
 *         (aria-level 3+), заголовок заменяется на <Breadcrumbs> — они
 *         показывают тот же заголовок, но с историей выбора перед ним.
 *
 * UX:     левый инсет здесь часть общего правила: любой текстовый блок
 *         верхнего уровня в <main> начинается в 12px от края (8px padding
 *         шапки + 4px собственный). Приветствие и сетка карточек стоят на той
 *         же линии — колонка контента должна иметь ОДНУ цифру отступа, а не
 *         «почти одну».
 * A11Y:   визуальный заголовок. Если экрану нужен заголовок в дереве
 *         доступности — оберните содержимое в <h1>, компонент не навязывает.
 *
 * @example
 * <PageTitle>My Tasks</PageTitle>
 */
export function PageTitle({ children }: { children: ReactNode }) {
  return <span className={s.mainHeaderTitle}>{children}</span>;
}
