/** Даты в проекте живут в двух видах: ДД.ММ.ГГГГ — то, что читает человек и
 *  что лежит в данных, и ГГГГ-ММ-ДД — то, что СРАВНИВАЕТСЯ. Второй вид выбран
 *  не из вкуса: у ISO-строк лексикографический порядок совпадает с
 *  хронологическим, поэтому весь диапазонный фильтр это обычные `>=` и `<=`
 *  над строками, без Date и без часовых поясов. */

/** Дата в ГГГГ-ММ-ДД по МЕСТНОМУ времени.
 *
 *  toISOString() здесь не годится принципиально: он переводит в UTC и в
 *  плюсовых поясах отдаёт ВЧЕРАШНИЙ день для всего, что раньше полудня — то
 *  есть «последние 30 дней» начинались бы на сутки раньше, и ошибку видно
 *  только до обеда. */
export function isoLocal(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/** ДД.ММ.ГГГГ → ГГГГ-ММ-ДД: строку из данных в строку, которую можно сравнить. */
export function dmyToIso(date: string): string {
  const [d, m, y] = date.split('.');
  return `${y}-${m}-${d}`;
}

/** ГГГГ-ММ-ДД → ДД.ММ.ГГ. Короткая подпись для контрола: год в реестре почти
 *  всегда один, а полная дата вдвое длиннее и ломает полосу фильтров. */
export function shortDate(iso: string): string {
  const [y, m, d] = iso.split('-');
  return `${d}.${m}.${y.slice(2)}`;
}

/** ГГГГ-ММ-ДД → ДД.ММ.ГГГГ. Полная дата — для поля ввода: в нём человек видит
 *  и правит то, что привык писать, а не ISO. */
export function isoToDmy(iso: string): string {
  const [y, m, d] = iso.split('-');
  return `${d}.${m}.${y}`;
}

/** Разбор того, что НАБРАЛ человек: ДД.ММ.ГГГГ → ГГГГ-ММ-ДД либо null.
 *
 *  Проверка обратным ходом обязательна. Регулярка пропускает «31.02.2026» —
 *  формат-то верный; Date молча превратит её в 3 марта, и фильтр отберёт не то,
 *  что просили, ни о чём не сообщив. Сверяем, что дата пережила конструктор без
 *  изменений: не пережила — значит её не существует. */
export function parseDmy(text: string): string | null {
  const m = /^(\d{1,2})[.,/-](\d{1,2})[.,/-](\d{4})$/.exec(text.trim());
  if (!m) return null;
  const [, d, mo, y] = m;
  const date = new Date(Number(y), Number(mo) - 1, Number(d));
  const iso = isoLocal(date);
  return iso === `${y}-${mo.padStart(2, '0')}-${d.padStart(2, '0')}` ? iso : null;
}

/** Первое число месяца, в который попадает дата. Календарь листается месяцами,
 *  и «текущий вид» — это всегда первое число, а не произвольный день. */
export function startOfMonth(iso: string): Date {
  const [y, m] = iso.split('-');
  return new Date(Number(y), Number(m) - 1, 1);
}

/** Сколько дней осталось до даты: отрицательное — срок уже прошёл, ноль —
 *  сегодня. Второй аргумент нужен проверке, в приложении берётся сегодня.
 *
 *  Обе даты приводятся к UTC-полуночи намеренно. Разница КАЛЕНДАРНЫХ дней не
 *  должна зависеть от перевода часов: в сутки со сдвигом обычное вычитание
 *  миллисекунд даёт 23 или 25 часов, и деление на сутки съедает либо
 *  добавляет день. У UTC-полуночей такой ошибки нет — разница всегда кратна
 *  86 400 000. */
export function daysUntil(iso: string, from = isoLocal(new Date())): number {
  return (utcDay(iso) - utcDay(from)) / 86_400_000;
}

function utcDay(iso: string): number {
  const [y, m, d] = iso.split('-');
  return Date.UTC(Number(y), Number(m) - 1, Number(d));
}

/** Форма слова «день» при числе: 1 день, 2 дня, 5 дней, 41 день.
 *
 *  Правило склонения не пишется руками (и тем более не «n === 1 ? день :
 *  дней» — на 41 и 22 это сразу видно): его знает Intl.PluralRules, стандарт
 *  платформы. Таблица здесь — только три слова, а не логика выбора. */
const RU_PLURAL = new Intl.PluralRules('ru-RU');
const DAY_FORM: Record<string, string> = { one: 'день', few: 'дня', many: 'дней' };

export function daysWord(n: number): string {
  return DAY_FORM[RU_PLURAL.select(Math.abs(n))] ?? 'дней';
}
