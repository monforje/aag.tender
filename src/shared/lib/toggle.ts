/** Переключить значение в списке мультивыбора: есть — убрать, нет — добавить.
 *  Живёт в shared, потому что нужен обеим сторонам мультивыбора — и полосе
 *  фильтров, которая правит доменные Filters, и универсальному <FacetFilter>,
 *  который про домен ничего не знает. */
export function toggle<T>(list: T[], item: T): T[] {
  return list.includes(item) ? list.filter((x) => x !== item) : [...list, item];
}
