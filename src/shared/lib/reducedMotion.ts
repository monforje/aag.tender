/** Просил ли пользователь выключить движение. Читается В МОМЕНТ ВОПРОСА, а не
 *  один раз при загрузке модуля: настройку меняют на живой странице, и
 *  запомненный ответ пережил бы её.
 *
 *  Нужна там, где анимацию НЕЛЬЗЯ выключить CSS-медиазапросом: длительность
 *  таймера, `behavior` у scrollIntoView, решение «стримить текст или показать
 *  целиком». Всё, что выключается в CSS, там и остаётся. */
export const reducedMotion = (): boolean =>
  typeof window !== 'undefined'
  && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
