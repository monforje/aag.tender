import { ChatRoundIcon } from '@solar-icons/react/bold/chat-round';
import { ChatRoundUnreadIcon } from '@solar-icons/react/bold/chat-round-unread';

/** Маркер переписки по ячейке — ДВА СОСТОЯНИЯ ОДНИМ ЗНАКОМ (решение
 *  владельца 25.08.2026, §2.4). Глифы названы владельцем поимённо:
 *  `chat-round-unread-bold` — есть непросмотренное, `chat-round-bold` — всё
 *  прочитано.
 *
 *  СЧЁТЧИКА-БАБЛА НЕТ. До 25.08 непросмотренность несла цифра в кружке; её
 *  упразднили, и это не упрощение, а исправление: «сколько именно
 *  комментариев» — не тот вопрос, который задают, ведя курсор по таблице.
 *  Вопрос ровно один — «есть ли тут что-то новое», и на него отвечает форма
 *  самого глифа (точка непрочитанного) плюс тон. Число живёт в шапке треда,
 *  где оно и нужно.
 *
 *  БЕРЁТСЯ ИЗ SOLAR, А НЕ РИСУЕТСЯ РЯДОМ с прочими пометками ячейки
 *  (`CorrectionMark`, `CoinMark`): те — знаки ДОМЕНА со своей геометрией и
 *  смыслом, которых в готовых наборах нет. «Комментарий» — интерфейсное
 *  понятие, и своя версия речевого пузыря отличалась бы от системной ровно
 *  ничем, кроме риска разъехаться.
 *
 *  Размер и цвет задаёт CSS потребителя (`.cmark`), а не пропы — как у
 *  <Icon> и у остальных ассетов ряда. */
export function CommentMark({ unread }: { unread?: boolean }) {
  const Glyph = unread ? ChatRoundUnreadIcon : ChatRoundIcon;
  return <Glyph aria-hidden="true" />;
}
