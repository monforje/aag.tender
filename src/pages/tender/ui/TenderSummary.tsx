import type { ReactNode } from 'react';
import { cx } from '@/shared/lib/cx';
import { Badge } from '@/shared/ui/Badge';
import { Icon, type IconName } from '@/shared/ui/Icon';
import { VisuallyHidden } from '@/shared/ui/VisuallyHidden';
import { bidsDue, STATUS, type DueMode, type TenderRow } from '@/entities/tender';
import s from './TenderSummary.module.css';

const TITLE_ID = 'tender-summary-title';

/** Режим срока → как дата выглядит В ПОКОЕ. Режимов пять, видов три: цвет
 *  отвечает на вопрос «нужно ли действовать сейчас», а не «какой сегодня
 *  день», поэтому «истёк» и «осталось три дня» тревожат одинаково и
 *  различаются подсказкой. Пустая запись — тоже вид, самый частый: только
 *  бледный пунктир, дата ничего не просит.
 *
 *  Глиф стоит ровно там, где цвет несёт смысл: тон danger не имеет права быть
 *  единственным каналом — при дальтонизме и в чёрно-белой печати красная дата
 *  и обычная не различаются никак. */
const DUE_LEVEL: Record<DueMode, { className?: string; icon?: IconName }> = {
  overdue: { className: s.dueAlert, icon: 'clock' },
  urgent: { className: s.dueAlert, icon: 'clock' },
  soon: { className: s.dueSoon },
  calm: {},
  idle: {},
};

/**
 * Шапка карточки тендера: название и пять полей, которыми тендер опознают.
 *
 * КОГДА:  первый блок на странице тендера, над остальным содержимым карточки.
 * НЕ ДЛЯ: строки реестра (там те же поля в колонках — см. TenderRegistryPage)
 *         и не для редактирования: это сводка, все значения только читаются.
 *         Понадобится такой же блок другому домену — сначала выносить в
 *         shared «карточку с полями», а не копировать этот файл: здесь
 *         доменного знания ровно на подбор пяти полей.
 *
 * UX:     отвечает на вопросы в порядке их возникновения: что это (название) →
 *         где это (объект) → когда (срок) → с кого спрашивать → в каком
 *         состоянии → какие работы. Название вынесено НАД карточкой и стоит
 *         на общей колонке контента (12px) — это заголовок экрана, а внутри
 *         рамки оно читалось бы как ещё одно значение в списке. Остальное —
 *         ровный список: пять полей одного веса и есть пять полей одного
 *         веса, и раскладывать их в колонки значило бы соврать про приоритет.
 *         Плитка с глифом у каждой строки даёт якорь для взгляда — по списку
 *         из пяти подписей глаз скользит, по чередованию значков попадает.
 *         Реакции на курсор нет НИГДЕ, кроме даты срока: остальное — подписи,
 *         а не контролы, и подсветка обещала бы клик, которого не будет. У
 *         даты hover есть, потому что там ЕСТЬ что показать — расшифровку
 *         режима. В покое дата работает ШРИФТОМ (цвет + пунктирное
 *         подчёркивание), по наведению добавляется самая лёгкая заливка шкалы:
 *         пунктир сообщает, что пояснение существует, до того как курсор туда
 *         попал, — иначе о нём можно не узнать вовсе.
 *         Единственное цветное пятно — состояние: капсула статуса и сама дата
 *         срока, если он поджимает. Остальное намеренно серо-чёрное, иначе
 *         акцент не работает.
 *         Меню «⋮» из макета не перенесено: действий у карточки пока нет, а
 *         кнопка, открывающая пустоту, хуже её отсутствия (то же правило, что
 *         у <ScreenPlaceholder>). Крупной плитки с глифом у названия тоже
 *         нет: у одного заголовка на экране нет соседей, от которых его надо
 *         отличать значком.
 * A11Y:   поля — настоящий <dl>: скринридер читает их парами «подпись —
 *         значение», а не сплошным текстом. Название страницы здесь и есть
 *         <h1> (в шапке экрана стоят крошки, заголовка там нет), и по нему же
 *         именуется сам список (aria-labelledby): ссылаться на заголовок
 *         снаружи можно, IDREF границ элемента не знает. Глифы плиток
 *         декоративны и скрыты (aria-hidden внутри <Icon>): смысл строки
 *         несёт её подпись.
 *
 * @example
 * <TenderSummary tender={tender} />
 */
export function TenderSummary({ tender }: { tender: TenderRow }) {
  const status = STATUS[tender.status];
  const due = bidsDue(tender);
  const level = DUE_LEVEL[due.mode];

  return (
    <>
      {/* Название стоит НАД карточкой и вне её рамки: это заголовок экрана, а
          не первое поле сводки. Левый инсет ему не нужен — паддинг
          .scroll-area--page и есть общая колонка контента в 12px, та же, на
          которой стоят крошки. */}
      <h1 className={s.summaryTitle} id={TITLE_ID}>{tender.title}</h1>

      <dl className={s.summary} aria-labelledby={TITLE_ID}>
        {/* Разделитель склеен с проектом в один флекс-элемент намеренно: на
            половинной ширине строка переносится, и болтающаяся в конце первой
            строки точка читалась бы как опечатка. Переносится «· Корпус 1»
            целиком — знак препинания принадлежит тому, что за ним. */}
        <Field icon="buildings2" label="Объект">
          {tender.portfolio}
          <span><span className={s.fieldSep}>·</span> {tender.project}</span>
        </Field>

        {/* Состояние срока несёт САМА дата, а не подпись рядом с ней: два
            элемента про одно и то же («15.07.2026» и «истёк 36 дней назад»)
            заставляли читать строку дважды. Расшифровка целой фразой уехала в
            подсказку по наведению, а для скринридера лежит текстом рядом —
            ему подсказку не навести. */}
        <Field icon="calendarSm" label="Срок сбора КП">
          <span className={cx(s.due, level.className)} data-hint={due.hint}>
            {level.icon ? <Icon name={level.icon} /> : null}
            {tender.end}
          </span>
          <VisuallyHidden>{due.hint}</VisuallyHidden>
        </Field>

        <Field icon="person" label="Ответственный">{tender.owner}</Field>

        {/* Тон и глиф приходят из STATUS: одно состояние — один цвет и один
            знак в таблице, в фильтре и здесь. */}
        <Field icon="flag" label="Статус">
          <Badge tone={status.tone} icon={status.icon}>{status.label}</Badge>
        </Field>

        <Field icon="sledgehammer" label="Вид работ">{tender.kind}</Field>
      </dl>
    </>
  );
}

/** Строка «плитка — подпись — значение». Локальная и безымянная снаружи:
 *  вынести её в shared можно будет, когда появится второй экран с полями, —
 *  сейчас это просто способ не писать одну и ту же разметку пять раз. */
function Field({ icon, label, children }: {
  icon: IconName;
  label: string;
  children: ReactNode;
}) {
  return (
    <div className={s.field}>
      <span className={s.fieldTile}><Icon name={icon} /></span>
      <dt className={s.fieldLabel}>{label}</dt>
      <dd className={s.fieldValue}>{children}</dd>
    </div>
  );
}
