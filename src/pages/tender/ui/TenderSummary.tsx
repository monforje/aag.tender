import { useState, type ReactNode } from 'react';
import { cx } from '@/shared/lib/cx';
import { dmyToIso } from '@/shared/lib/date';
import { DatePicker } from '@/shared/ui/DatePicker';
import { InlineInput } from '@/shared/ui/InlineInput';
import { Badge } from '@/shared/ui/Badge';
import { Icon, type IconName } from '@/shared/ui/Icon';
import { VisuallyHidden } from '@/shared/ui/VisuallyHidden';
import { bidsDue, STATUS, type DueMode, type TenderRow } from '@/entities/tender';
import s from './TenderSummary.module.css';

const TITLE_ID = 'tender-summary-title';

/** Режим срока → как дата выглядит В ПОКОЕ. Режимов пять, видов три: цвет
 *  отвечает на вопрос «нужно ли действовать сейчас», а не «какой сегодня
 *  день», поэтому «истёк» и «осталось три дня» тревожат одинаково и
 *  различаются подсказкой. Пустая запись — тоже вид, самый частый: дата
 *  ничего не просит.
 *
 *  Глиф стоит ровно там, где цвет несёт смысл: тон danger не имеет права быть
 *  единственным каналом — при дальтонизме и в чёрно-белой печати красная дата
 *  и обычная не различаются никак. Отдельного значка рядом со значением
 *  больше нет: тревогу несёт САМА иконка поля, календарь сменяется часами.
 *  Два глифа в одной строке про один и тот же срок — это два раза об одном. */
const DUE_LEVEL: Record<DueMode, { className?: string; icon: IconName }> = {
  overdue: { className: s.fieldAlert, icon: 'clock' },
  urgent: { className: s.fieldAlert, icon: 'clock' },
  soon: { icon: 'calendarSm' },
  calm: { icon: 'calendarSm' },
  idle: { icon: 'calendarSm' },
};

/**
 * Шапка карточки тендера: название со статусом и четыре редактируемых поля.
 *
 * КОГДА:  первый блок на странице тендера, над остальным содержимым карточки.
 * НЕ ДЛЯ: строки реестра (там те же поля в колонках — см. TenderRegistryPage).
 *         Понадобится такой же блок другому домену — сначала выносить в
 *         shared «карточку с полями», а не копировать этот файл: здесь
 *         доменного знания ровно на подбор четырёх полей.
 *
 * UX:     отвечает на вопросы в порядке их возникновения: что это (название) →
 *         в каком состоянии (статус) → где (объект) → когда (срок) → с кого
 *         спрашивать → какие работы.
 *
 *         СТАТУС РАСКРЫВАЕТСЯ ПО НАВЕДЕНИЮ. В покое это кружок с глифом
 *         своего тона, под курсором капсула разъезжается вбок и показывает
 *         подпись. Так можно, потому что справа от капсулы НИЧЕГО НЕТ:
 *         запрет каталога состояний на «сдвиг под курсором» защищает от
 *         уезжающей цели, а здесь двигаться нечему и кликать не по чему
 *         (рецепт 10 в global.css). В покое состояние всё равно читается
 *         двумя каналами — тон заливки и глиф, — так что подпись раскрывает
 *         третий, а не единственный. На тач-устройствах (@media hover:none)
 *         капсула раскрыта всегда: там наведения не существует.
 *
 *         ПОЛЯ — СТРОКА «ГЛИФ · ПОДПИСЬ · ЗНАЧЕНИЕ», по две в два ряда.
 *         Подпись вернулась в свою колонку и перестала быть капителью: над
 *         значением она была заголовком ячейки, слева от него — снова
 *         колонка, а капитель в колонке читается как шум.
 *
 *         ЗНАЧЕНИЕ — <InlineInput>: поле, которое в покое выглядит как
 *         обычный текст. Рамка у каждого из четырёх полей превратила бы
 *         сводку в анкету, а сводку в первую очередь ЧИТАЮТ. Поверхность
 *         общая с кнопкой <DatePicker> — глобальная .inline-edit
 *         (global.css, раздел 1-b): все четыре строки обязаны быть
 *         неотличимы в покое, иначе одна из них читается как единственная
 *         редактируемая.
 *
 *         СРОК — <DatePicker>, календарь shadcn в поповере. До него тут стоял
 *         нативный <input type="date">, и он проиграл в двух вещах сразу:
 *         попап рисует браузер (в интерфейс не вписывается), а формат показа
 *         берётся из локали БРАУЗЕРА, а не страницы — на en-US тот же тендер
 *         показывал 07/15/2026 и расходился с колонкой реестра. Плюс родной
 *         значок календаря прижат к дальнему краю поля, то есть в колонке под
 *         400px уезжал от даты на пол-строки. <DatePicker> держит формат
 *         ДД.ММ.ГГГГ всегда и ставит глиф вплотную к дате.
 *
 *         Введённое НИКУДА НЕ СОХРАНЯЕТСЯ: сохранять пока некуда, поля
 *         неуправляемые (defaultValue). При переходе на другой тендер
 *         key={tender.id} пересоздаёт их — иначе в новой карточке остались бы
 *         значения предыдущей.
 * A11Y:   поля — настоящий <dl>: скринридер читает их парами «подпись —
 *         значение». Глиф лежит ВНУТРИ <dt>, потому что обёртка-<div> в <dl>
 *         имеет право содержать только <dt> и <dd>. Видимой подписи у поля
 *         ввода нет, поэтому та же подпись уходит в aria-label: <dt> рядом
 *         именем поля для скринридера не считается. Название страницы здесь
 *         и есть <h1> (в шапке экрана крошки), по нему же именуется список
 *         (aria-labelledby). Подпись статуса раскрывается визуально, но из
 *         DOM не исчезает — скринридер читает её всегда; слово «Статус:»
 *         рядом лежит скрытым, иначе капсула читается голым значением.
 *
 * @example
 * <TenderSummary tender={tender} />
 */
export function TenderSummary({ tender }: { tender: TenderRow }) {
  const status = STATUS[tender.status];
  const due = bidsDue(tender);
  const level = DUE_LEVEL[due.mode];

  return (
    <>
      {/* Название стоит НАД карточкой и вне её рамки: это заголовок экрана, а
          не первое поле сводки. Левый инсет ему не нужен — паддинг
          .scroll-area--page и есть общая колонка контента в 12px, та же, на
          которой стоят крошки.

          Статус стоит ЗДЕСЬ, рядом с названием, а не полем в сводке: это не
          справочное значение в одном ряду с видом работ, а ответ на вопрос
          «жив ли тендер», и его читают одновременно с названием. Подпись
          обёрнута дважды намеренно: внешний span — анимируемая колейка
          (0fr → 1fr), внутренний прячет текст, пока колейка схлопнута.
          Единственный способ доехать до ширины ПО СОДЕРЖИМОМУ без магического
          числа в max-width, которое разъедется на первом же длинном статусе. */}
      <div className={s.summaryHead}>
        <h1 className={s.summaryTitle} id={TITLE_ID}>{tender.title}</h1>
        <VisuallyHidden>Статус:</VisuallyHidden>
        <Badge className={s.status} tone={status.tone} icon={status.icon}>
          <span className={s.statusLabel}><span>{status.label}</span></span>
        </Badge>
      </div>

      <dl className={s.summary} aria-labelledby={TITLE_ID} key={tender.id}>
        {/* Портфель и проект склеены в ОДНО значение через «·»: это путь, а не
            два независимых поля, и в поле ввода он и правится целиком.
            Приглушить сам разделитель больше нечем — подкрасить кусок текста
            внутри <input> нельзя; цена того, что «объект» стал редактируемым. */}
        <Field icon="buildings2" label="Объект">
          <InlineInput label="Объект" value={`${tender.portfolio} · ${tender.project}`} />
        </Field>

        {/* Состояние срока несёт САМА дата, а не подпись рядом с ней: два
            элемента про одно и то же («15.07.2026» и «истёк 36 дней назад»)
            заставляли читать строку дважды. Расшифровка целой фразой уехала в
            подсказку по наведению на всю строку поля, а для скринридера лежит
            текстом рядом — ему подсказку не навести. */}
        <Field
          icon={level.icon}
          className={level.className}
          label="Срок сбора КП"
          hint={due.hint}
        >
          <DateValue label="Срок сбора КП" value={dmyToIso(tender.end)} />
        </Field>

        <Field icon="person" label="Ответственный">
          <InlineInput label="Ответственный" value={tender.owner} />
        </Field>

        <Field icon="sledgehammer" label="Вид работ">
          <InlineInput label="Вид работ" value={tender.kind} />
        </Field>
      </dl>
    </>
  );
}

/** Строка «глиф · подпись · значение», значение — поле ввода. Локальная и
 *  безымянная снаружи: вынести её в shared можно будет, когда появится второй
 *  экран с полями, — сейчас это способ не писать одну и ту же разметку
 *  четыре раза.
 *
 *  hint включает подсказку на ВСЕЙ строке, а не на значении: цель шире, а
 *  ::after у <input> не бывает — у заменяемых элементов псевдоэлементов нет.
 *  Заодно это и есть причина, по которой подсказка не осталась на дате. */
function Field({ icon, label, children, hint, className }: {
  icon: IconName;
  label: string;
  children: ReactNode;
  hint?: string;
  className?: string;
}) {
  return (
    <div className={cx(s.field, className)} data-hint={hint}>
      <dt className={s.fieldLabel}><Icon name={icon} />{label}</dt>
      <dd className={s.fieldValue}>
        {children}
        {hint ? <VisuallyHidden>{hint}</VisuallyHidden> : null}
      </dd>
    </div>
  );
}

/** Значение-дата. Состояние ЗДЕСЬ, а не в <TenderSummary>: <DatePicker>
 *  управляемый, ему нужен value, а key={tender.id} стоит на <dl> — то есть
 *  граница пересоздания проходит ниже сводки, и состояние обязано лежать под
 *  ней, иначе на другом тендере останется дата предыдущего. */
function DateValue({ label, value }: { label: string; value: string }) {
  const [iso, setIso] = useState(value);
  return <DatePicker value={iso} onChange={setIso} label={label} />;
}
