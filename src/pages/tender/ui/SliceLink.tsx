import { useState } from 'react';
import { cx } from '@/shared/lib/cx';
import { Icon } from '@/shared/ui/Icon';
import s from './SliceLink.module.css';

/**
 * «Скопировать ссылку на срез» — рабочий контекст сравнения одной ссылкой
 * (§3.5, `state.md` §1, `table.md` §8).
 *
 * КОГДА:  НА СТРОКЕ ВКЛАДОК рабочего места, справа за распоркой (место
 *         зафиксировано владельцем 25.08.2026): пользователь копирует
 *         контекст, не уходя со сравнения.
 * НЕ ДЛЯ: выгрузки данных (см. ExportDialog — там .xlsx и полный состав) и
 *         постоянной ссылки на тендер: здесь передают ВИД, а не документ.
 *
 * UX:     ОДИН ПИЛЮЛЬ-БЛОК, как в Figma и Claude Design (форма — правка
 *         владельца): иконка ссылки · усечённый URL моно · кнопка копирования.
 *         Без разбора параметров и без тоста: разбор «что именно поедет»
 *         никто не читает, а тост поверх таблицы перекрывает то, ссылку на
 *         что копируют. Подтверждение живёт В САМОЙ КНОПКЕ — глиф на две
 *         секунды меняется на галочку, там же, куда человек только что
 *         смотрел.
 *         URL УСЕЧЁН ВИЗУАЛЬНО, А НЕ ОБРЕЗАН: в буфер уходит адрес целиком.
 *         Права на срез повторно проверяет сервер — ссылка не даёт доступа,
 *         она только воспроизводит вид.
 * A11Y:   адрес — текст, его можно выделить и скопировать руками, если
 *         буфер недоступен (http без TLS, отказ в разрешении). Кнопка
 *         называет действие и состояние; смена глифа продублирована
 *         aria-label.
 *
 * @example
 * <SliceLink />
 */
export function SliceLink() {
  const [done, setDone] = useState(false);
  /* Адрес читается В МОМЕНТ КЛИКА, а не в рендере: срез меняется каждой
     галочкой, и запомненная строка устарела бы к первому же нажатию. */
  const shown = typeof window === 'undefined' ? '' : window.location.href.replace(/^https?:\/\//, '');

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(window.location.href);
      setDone(true);
      window.setTimeout(() => setDone(false), 2000);
    } catch {
      /* Буфер недоступен (http без TLS, отказ в разрешении) — молча ничего
         не делаем: адрес остаётся выделяемым текстом рядом, и это честный
         запасной путь. Ложная галочка «скопировано» была бы хуже. */
    }
  };

  return (
    <span className={s.pill}>
      <Icon name="link" className={s.linkIcon} />
      <span className={s.url} title={shown}>{shown}</span>
      <button
        type="button"
        className={cx(s.copy, done && s.isDone)}
        aria-label={done ? 'Ссылка на срез скопирована' : 'Скопировать ссылку на срез'}
        title="Скопировать ссылку на этот срез сравнения"
        onClick={copy}
      >
        <Icon name={done ? 'checkCircle' : 'copy'} />
      </button>
    </span>
  );
}
