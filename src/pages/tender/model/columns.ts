/** РАСЧЁТ ШИРИН КОЛОНОК СРАВНЕНИЯ КП — единственное место, где решается,
 *  сколько пикселей достаётся каждой колонке. Чистая функция: одни входы —
 *  одна раскладка, поэтому проверяется `columns.check.ts` без DOM.
 *
 *  ИСТОРИЯ. До 24.08.2026 полом колонки подрядчика служило её ПОЛНОЕ ИМЯ
 *  (замерщик в TenderCompare), и колонки выходили неравными — решение
 *  владельца того дня. Отменено тем же владельцем (24.08.2026): ширина всех
 *  колонок КП ФИКСИРОВАНА одной константой BID_FIXED, имя обрезается
 *  многоточием, полное название всплывает по наведению (<Tooltip>).
 *
 *  ДВА РЕЖИМА.
 *  «Влезает» — левые колонки стоят от базы вниз до своих полов (жмутся ровно
 *  настолько, чтобы название удержало минимум), подрядчикам достаётся ровно
 *  BID_FIXED, название забирает весь остаток.
 *  «Панорама» — даже на половах не влезает: левые на минимумах, все колонки
 *  КП на BID_FIXED, названию — его минимум, лента прокручивается.
 *
 *  ЗДЕСЬ ЖЕ ЛИМИТ НАЗВАНИЯ В ЗНАКАХ (`titleLimit`): ширина колонки — его
 *  единственный вход, и держать их в разных файлах значило бы однажды
 *  подвинуть одно без другого.
 *
 *  МОНОТОННОСТЬ ГАРАНТИРОВАНА: расширение доступной ширины никогда не сужает
 *  колонку — проверяется в columns.check.ts, потому что глазами на живом
 *  экране обратное не поймать (числа правдоподобны в любом порядке).
 */

/* ── конфиг ────────────────────────────────────────────────────────────────
   Все числа системы в одном месте — вместо разбросанных по ступеням CSS
   переменных. База — комфортная ширина; пол — последняя ступень перед тем,
   как содержимое колонки перестаёт читаться. */

/* ПОЛ ЛЕВОЙ КОЛОНКИ — ПО ЕЁ ЗАГОЛОВКУ, а не по значению (24.08.2026, вторая
   волна). Прежние 76/60/72 были сняты с содержимого ячеек, и на тесной ленте
   шапка читалась «Количес… Едини… Разбр…»: колонка переставала называть себя
   раньше, чем переставало помещаться её число. Цифры замерены canvas'ом по
   живому шрифту заголовка (14px/600) — «Количество» 82px, «Единица» 61,
   «Разброс» 58 — плюс паддинги 8+8 и пара пикселей на округление. У разброса
   пол считается не по заголовку, а по САМОЙ ШИРОКОЙ ячейке: «63,5 %» рядом с
   брелоком высокого разброса (24px + отступ). */
const LEAD = {
  /** Количество: заголовок 82 + паддинги; значение «1 234 567» уже. */
  qty: { base: 106, min: 102 },
  /** Единица: заголовок 61 + паддинги; значения «компл.» и счёт секции
     *  «ПОЗИЦИЙ» (13px капсом ≈ 60px + паддинги). */
  unit: { base: 100, min: 92 },
  /** Разброс: «63,5 %» + брелок 24px + паддинги. */
  spread: { base: 96, min: 90 },
  /** УСЛОВНЫЙ СТОЛБЕЦ «ПОТЕНЦИАЛ» (§1.6). Пол 120px — не с потолка: значение
   *  печатается компактным форматом («164 тыс. ₽» ≈ 74px табличными 14px),
   *  под ним подпись «3 из 10» ≈ 46px, плюс паддинги 8+8. База шире на
   *  комфортный воздух. Колонка появляется ПО ГАЛОЧКЕ, и её ширина берётся
   *  из того же бюджета, что у соседей: включение потенциала жмёт название,
   *  а не колонки КП — те фиксированы. */
  potential: { base: 138, min: 120 },
} as const;

/** Название позиции: ниже этого якорная колонка перестаёт называть строку.
 *  280, а не прежние 200 (24.08.2026, вторая волна): на реальной смете
 *  названия длинные («Крышка на лоток с заземлением осн. 200 L 2000…»), и на
 *  200px в панораме от них оставалось два слова — колонка-якорь превращалась в
 *  подпись «Щит распределитель…». Лишние 80px лента и так панорамирует. */
const TITLE_MIN = 280;

/** То же в РАЗВЁРНУТОМ режиме — тумблер «Развернуть названия позиций»
 *  (решение владельца 24.08.2026, третья волна). Смету читают двумя разными
 *  способами: обычно — сравнивая цены столбиком, где длинное имя только
 *  отнимает место у колонок КП, но иногда — разбираясь, ЧТО именно за работа,
 *  и тогда «Кабель силовой, не р…» бесполезен.
 *
 *  440, а не «сколько влезет»: столько занимает левый блок целиком за вычетом
 *  трёх своих колонок (102+92+90) и резерва под ключ — верхняя граница,
 *  названная владельцем. Вместе со второй строкой (`titleLimit(w, 2)`) это
 *  ~90 знаков против 28 в обычном режиме. Цена честная и предсказуемая: лента
 *  уходит в панораму на 160px раньше, поэтому режим и сделан тумблером, а не
 *  автоматикой по длине названий — «иногда» решает человек. */
const TITLE_WIDE = 440;

/** ШИРИНА КОЛОНКИ КП — одна для всех подрядчиков. Число снято с живого экрана
 *  24.08.2026 как фактическая ширина колонки «АО «МетСнаб»» при прежнем
 *  алгоритме (пол по имени): владелец попросил зафиксировать именно её.
 *  Имя длиннее обрезается многоточием, полное название — по наведению.
 *
 *  РАСШИРЕНО 180 → 212 (решение владельца 24.08.2026, вторая волна): на 180px
 *  строка карточки «100 % / ЗАПОЛНЕНО / сумма» не помещалась — подпись
 *  наезжала на итог. Число складывается из содержимого, а не из вкуса:
 *  поля 12+12, блок полноты ≈66 (подпись «ЗАПОЛНЕНО» капителью 10/12), зазор
 *  10, итог ≈110 («27 764 142 ₽» табличными цифрами 16/21) — 210, округлено
 *  вверх до чётного.
 *
 *  212 → 228 (правка владельца 25.08.2026, вечер): «чуть-чуть увеличим ширину
 *  шапки». Шестнадцать пикселей идут не в воздух, а двум конкретным строкам —
 *  подвалу карточки, где пять элементов делили 188px содержимого и «Уточняется»
 *  резалось на четвёртой букве, и шапке, куда добавился селект редакции с
 *  названием-фразой. */
export const BID_FIXED = 228;

/** ШИРИНА КОЛОНКИ «№» (§7 правок владельца 25.08.2026, вечер). Номер позиции
 *  переехал сюда из левого верхнего угла колонки-якоря: своей строкой над
 *  названием он поднимал КАЖДУЮ строку таблицы на 13px ради служебного числа,
 *  а выровнять по нему было нечего — соседи по строке (объём, единица) стоят
 *  по центру своей высоты, номер висел выше них.
 *
 *  44px — это 12px левого поля (общая колонка контента страницы), три знака
 *  табличными 12px (~21px) и 8px правого поля. Фиксирована и в раздаче
 *  бюджета не участвует: номеру нечем пользоваться от лишних пикселей, а
 *  разъезжающаяся ширина сделала бы номера соседних строк невыровненными на
 *  ровном месте. */
export const NUM_FIXED = 44;

/** ПОТОЛОК НАЗВАНИЯ ПОЗИЦИИ В ЗНАКАХ (решение владельца 24.08.2026): длинное
 *  название режется СЧЁТОМ СИМВОЛОВ, а не CSS-многоточием. Причина не
 *  косметическая: `text-overflow: ellipsis` заставляет движок мерить текст
 *  каждой ячейки заново на КАЖДОМ изменении ширины колонки — а она меняется
 *  каждый кадр, пока прячется сайдбар или едет панель «Анализ ИИ», и колонка
 *  названий видимо «кипела». Счёт знаков от ширины даёт то же на глаз, но
 *  строка-результат меняется лишь при смене САМОГО ЛИМИТА (целое число), то
 *  есть в разы реже кадров. */
export const TITLE_CHARS = 40;

/** Средняя ширина знака названия — 7,3px. Замерено canvas'ом по живому шрифту
 *  ячейки (14px/600, системный sans) на самих названиях сметы. Оценка, а не
 *  замер КАЖДОЙ строки: точный замер вернул бы ровно ту работу, ради ухода от
 *  которой лимит и заведён. */
const TITLE_CHAR_PX = 7.3;

/** Ниже этого названия перестаёт называть позицию вовсе. */
const TITLE_CHARS_MIN = 14;

/** Сколько знаков названия помещается в колонку: не длиннее потолка и не
 *  шире 3/4 её ширины — правая четверть остаётся воздухом и местом под
 *  ключ (решение владельца 24.08.2026). `undefined` — кадр до первого
 *  замера: до него берётся потолок.
 *
 *  `lines` — сколько строк отдано названию (2 в развёрнутом режиме). Потолок
 *  и вместимость растут вместе с ним, а не только вместимость: 40 знаков —
 *  это потолок ОДНОЙ строки.
 *
 *  ponytail: перенос отдан браузеру, третью строку никто не сторожит. Запас
 *  ровно в той самой четверти ширины: текст, обрезанный по 3/4 вместимости
 *  двух строк, не набирает третью даже на самых неудачных переносах. Понадобится
 *  жёсткая гарантия — это `-webkit-line-clamp` на обёртке названия ВМЕСТЕ с
 *  ключом (иначе ключ уедет на свою строку), и стоить она будет перемера
 *  текста на каждой смене ширины — того самого, ради ухода от которого лимит
 *  и заведён. */
export function titleLimit(titleWidth?: number, lines = 1): number {
  const ceiling = TITLE_CHARS * lines;
  if (titleWidth == null) return ceiling;
  const fits = Math.floor((titleWidth * 0.75) / TITLE_CHAR_PX) * lines;
  return Math.max(TITLE_CHARS_MIN, Math.min(ceiling, fits));
}

const LEAD_BASE = LEAD.qty.base + LEAD.unit.base + LEAD.spread.base;
const LEAD_MIN = LEAD.qty.min + LEAD.unit.min + LEAD.spread.min;

export interface ColumnLayoutInput {
  /** Видимая ширина скроллблока ленты, px (clientWidth: вертикальный
   *  скроллбар уже исключён). */
  available: number;
  /** Колонки КП по порядку таблицы — нужен только состав id. */
  bids: ReadonlyArray<{ id: string }>;
  /** Развёрнутые названия: колонка-якорь получает TITLE_WIDE вместо
   *  TITLE_MIN. Тумблер в окне параметров. */
  wideTitle?: boolean;
  /** Включён условный столбец «Потенциал» (§1.6): в левом блоке появляется
   *  пятая колонка. Флагом, а не «списком колонок»: колонка ровно одна и
   *  ровно одна её и включает. */
  potential?: boolean;
}

export interface ColumnLayout {
  /** Колонка «№» — константа NUM_FIXED. Полем, а не числом по месту: ширины
   *  читают и <colgroup>, и сумма ширины таблицы, и мост липкости. */
  num: number;
  qty: number;
  unit: number;
  spread: number;
  /** Ширина столбца «Потенциал»; `undefined` — столбец выключен, и <col>
   *  для него не рисуется вовсе. */
  potential?: number;
  title: number;
  /** Ширины колонок КП по id подрядчика — у всех одинаково. */
  bids: Record<string, number>;
  /** Сумма фиксированных ширин больше доступного места: лента панорамирует. */
  pan: boolean;
}

/* ЛЕВЫЙ БЛОК: раздача бюджета от полов по запасу каждой колонки. Целые
   остатки распределяются ДО КОНЦА по фиксированному порядку — сумма трёх
   ширин равна бюджету точно, поэтому название (оно получает всё, что
   осталось после левого блока и долей КП) растёт монотонно с окном и не
   дрожит на границах округления. */
function allocLeads(total: number, potential: boolean): {
  qty: number; unit: number; spread: number; potential?: number;
} {
  const cols = [
    { min: LEAD.qty.min, room: LEAD.qty.base - LEAD.qty.min },
    { min: LEAD.unit.min, room: LEAD.unit.base - LEAD.unit.min },
    { min: LEAD.spread.min, room: LEAD.spread.base - LEAD.spread.min },
    ...(potential
      ? [{ min: LEAD.potential.min, room: LEAD.potential.base - LEAD.potential.min }]
      : []),
  ];
  const allRoom = cols.reduce((acc, c) => acc + c.room, 0);
  const extra = Math.max(0, Math.min(total, LEAD_BASE) - LEAD_MIN);
  const extras = cols.map((c) => Math.floor((extra * c.room) / allRoom));
  /* Остаток считается ПО ДОБАВКАМ, а не по полным ширинам: смешать их здесь
     значило бы, что топ-ап не срабатывает никогда, бюджет недирается на
     число усечений, и название дрожит на каждом шаге окна. */
  let rest = extra - extras.reduce((acc, w) => acc + w, 0);
  for (let i = 0; rest > 0 && i < cols.length; i++) {
    const take = Math.min(rest, cols[i].room - extras[i]);
    extras[i] += take;
    rest -= take;
  }
  return {
    qty: cols[0].min + extras[0],
    unit: cols[1].min + extras[1],
    spread: cols[2].min + extras[2],
    ...(potential ? { potential: cols[3].min + extras[3] } : {}),
  };
}

export function computeColumnLayout({
  available, bids, wideTitle, potential,
}: ColumnLayoutInput): ColumnLayout {
  const on = potential === true;
  /* Бюджет левого блока растёт вместе с условным столбцом — и база, и пол:
     иначе включение «Потенциала» либо не давало бы ему места вовсе, либо
     съедало его у названия молча. */
  const leadBase = LEAD_BASE + (on ? LEAD.potential.base : 0);
  const leadMin = LEAD_MIN + (on ? LEAD.potential.min : 0);
  const sumFixed = Math.max(bids.length, 1) * BID_FIXED;
  const fixedBids = (): Record<string, number> =>
    Object.fromEntries(bids.map(({ id }) => [id, BID_FIXED]));
  /* Единственное, что меняет режим, — ПОЛ названия. Ни бюджет левого блока,
     ни ширины КП его не касаются: развёрнутое название забирает место у
     панорамы, а не у соседних колонок. */
  const titleMin = wideTitle ? TITLE_WIDE : TITLE_MIN;

  /* Панорама: места нет даже на половах левого блока. Колонка «№» входит в
     обязательную часть целиком — она константа и жаться ей нечем. */
  if (available < NUM_FIXED + leadMin + titleMin + sumFixed) {
    return {
      num: NUM_FIXED,
      qty: LEAD.qty.min, unit: LEAD.unit.min, spread: LEAD.spread.min,
      ...(on ? { potential: LEAD.potential.min } : {}),
      title: titleMin, bids: fixedBids(), pan: true,
    };
  }

  /* Влезает: левые колонки жмутся от базы вниз ровно настолько, чтобы
     название удержало минимум; весь остаток забирает оно целиком. */
  const leadTotal = Math.min(leadBase, available - NUM_FIXED - titleMin - sumFixed);
  const lead = allocLeads(leadTotal, on);
  const used = NUM_FIXED + lead.qty + lead.unit + lead.spread + (lead.potential ?? 0);
  const title = available - used - sumFixed;

  return {
    num: NUM_FIXED, ...lead, title: Math.max(title, titleMin), bids: fixedBids(), pan: false,
  };
}
