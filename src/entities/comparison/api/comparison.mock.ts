/* Детерминированная «случайность»: хэш строки → множитель в [lo; hi] с шагом
   step. Одинаковый при каждом запуске, потому и заменяет рукописные таблицы:
   260 расценок вокруг цен файла руками держать никто не будет. */
const hash = (str: string): number =>
  [...`${str}axp`].reduce((acc, ch) => (acc * 31 + ch.charCodeAt(0)) >>> 0, 7);

/** Множитель подрядчика для позиции: персональный УРОВЕНЬ цен подрядчика плюс
 *  разброс по строкам — материалы гуляют шире работ, как в живых торгах.
 *
 *  ДВЕ ПРАВКИ 24.08.2026 (третья волна), обе от одного симптома: на десяти
 *  колонках две пары КП совпали построчно до рубля (pes↔ekm 55 позиций из 65,
 *  mvp↔rek 49). Сравнение, где два предложения одинаковы до копейки, читается
 *  поломкой таблицы, а не совпадением.
 *
 *  1. УРОВЕНЬ — СВОЙ У КАЖДОГО, И ОН ЖЕ ЦЕНТР ОБЕИХ ВИЛОК. Раньше персональной
 *     была только вилка работ, а материалы гуляли в общих ±8 % вокруг цен
 *     файла — то есть у всех подрядчиков одинаково. А основная часть бюджета
 *     этой сметы лежит именно в материалах (светильники дешевле 50 000 за
 *     штуку), и «кто дороже» решал не уровень подрядчика, а бросок хэша.
 *     Отсюда же был и трюк с зерном «vgs8»: без него участник обгонял цены
 *     файла и переворачивал ранжир. Теперь уровень — вход, и ранжир
 *     ПОСТРОЕН, а не подобран.
 *  2. ШАГ ВИЛКИ — 1/1008, А НЕ 1/16. Семнадцать ступеней на общую вилку — это
 *     семнадцать возможных цен на позицию: совпадения были неизбежны. */
const factor = (seed: string, id: string, base: number, level: number): number => {
  const h = hash(`${seed}:${id}`);
  const room = base >= 50000 ? 0.07 : 0.08;
  return level - room + ((h % 1009) / 1008) * room * 2;
};

type Bid = Record<string, number>;

/** КП конкурента: цены файла × персональная вилка; пропущенные id — честный
 *  пробел данных (ключа нет). `level` — во сколько раз этот подрядчик В
 *  СРЕДНЕМ дороже цен файла: 0.96 — дешевле файла, 1.10 — заметно дороже.
 *  Уровни РАЗНЕСЕНЫ, но тесно — вся десятка укладывается в ±8 % вокруг файла.
 *  Шире нельзя: формула аномалии ищет выброс относительно того, как расходятся
 *  ОСТАЛЬНЫЕ участники строки, и подрядчик, стоящий на краю широкой сетки,
 *  получал пометку в половине своих строк — маркер «посмотри сюда» превращался
 *  в фон. Уже тоже нельзя: рубль не разрешает разницу в полпроцента, и колонки
 *  начинают совпадать построчно на дешёвых позициях.
 *
 *  ВЫШЕ ЕДИНИЦЫ — ТОЛЬКО У ПОЛНЫХ КП, и это условие ранжира демо-сцены:
 *  лидером обязана оставаться колонка из файла, а `rankBids` ставит НЕПОЛНОЕ
 *  предложение ниже любого полного независимо от суммы — значит опускать ниже
 *  файла можно ровно тех, у кого КП неполное. Ровнять же всех выше единицы
 *  нельзя: колонка файла оказывалась дешевле всей десятки разом, и формула
 *  аномалии честно помечала её выбросом почти в каждой строке. */
const rivalPrices = (
  seed: string, level: number, missing: string[], overrides?: Bid,
): Bid => {
  const out: Bid = {};
  for (const [id, base] of Object.entries(STM_PRICES)) {
    if (missing.includes(id)) continue;
    out[id] = overrides?.[id]
      ?? Math.max(1, Math.round(base * factor(seed, id, base, level)));
  }
  return out;
};

