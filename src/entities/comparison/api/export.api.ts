/** Имя файла: сущность_дата_время.xlsx (`table.md` §7). Считается здесь, а
 *  не в модалке: имя видно в модалке ДО выгрузки и приходит в ответе ПОСЛЕ —
 *  два места, одна формула. */
export function exportFileName(tenderId: string, now = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  const date = `${now.getFullYear()}-${p(now.getMonth() + 1)}-${p(now.getDate())}`;
  return `${tenderId}_sravnenie_${date}_${p(now.getHours())}${p(now.getMinutes())}.xlsx`;
}

/** Строка «Выбранные версии зафиксированы: …» — пятый пункт чеклиста, и
 *  единственный, который зависит от данных: выгрузка фиксирует ИМЕННО те
 *  версии, что открыты сейчас (`contractor.md` §2). */
export const exportVersionsLine = (
  picked: ReadonlyArray<{ name: string; version: string }>,
): string | null => (picked.length
  ? `Выбранные версии зафиксированы: ${picked.map((p) => `${p.name} ${p.version}`).join(', ')}`
  : null);

/** Результат запроса выгрузки. */
export interface ExportResult {
  fileName: string;
  /** Ссылка на готовый файл. Пусто — сервер принял задание, но файла ещё
   *  нет: у больших смет генерация асинхронна, и врать кнопкой «Скачать»,
   *  за которой ничего нет, нельзя. */
  url?: string;
}

/** Запросить файл. Мок задание ПРИНИМАЕТ, но ссылки не отдаёт — генератора
 *  .xlsx на клиенте нет и не будет (см. шапку файла), а подсовывать вместо
 *  него CSV с тем же расширением значило бы отдать пользователю сломанный
 *  документ вместо честного «готовится». Экран показывает это состоянием,
 *  а не молчанием. */
export async function requestExport(input: {
  tenderId: string;
  /** Версии, зафиксированные в выгрузке, — уходят в запрос вместе с ним. */
  versions: ReadonlyArray<{ contractorId: string; versionId: string }>;
}): Promise<ExportResult> {
  return { fileName: exportFileName(input.tenderId) };
}
