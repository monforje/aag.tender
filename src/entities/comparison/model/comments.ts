/** КОММЕНТАРИИ К ЯЧЕЙКЕ «позиция × подрядчик» — единственное место, где
 *  несопоставимость объясняется СЛОВАМИ поставщика (`comment.md`,
 *  `position-comments.md`). Без них аномалия и низкая цена остаются без
 *  возможного оправдания, и правило канона «низкая цена требует проверки
 *  состава» повисает.
 *
 *  ЖИВУТ В СЛАЙСЕ СРАВНЕНИЯ, а не в `entities/tender`, хотя канон называет
 *  документ `position-comments.md`. Проверка одна и та же — «кто это
 *  импортирует»: ключ треда это АДРЕС ЯЧЕЙКИ СРАВНЕНИЯ (`contractorId:
 *  positionId`), и знает такой адрес ровно один экран. Уехав в слайс тендера,
 *  комментарии унесли бы туда же понятие ячейки — и реестр тендеров начал бы
 *  зависеть от устройства таблицы сравнения.
 *
 *  ПРОСМОТРЕННОСТЬ — СОСТОЯНИЕ ЧИТАТЕЛЯ, а не записи: «непросмотрено» у меня
 *  и у коллеги разное. Поле живёт при комментарии, потому что ответ сервера
 *  персональный — он уже знает, кто спрашивает. */

/** Одна запись треда. Ответ отличается от корневой записи ТОЛЬКО наличием
 *  `parentId`: отдельного типа у ответа нет — иначе ответ на ответ потребовал
 *  бы третьего. */
export interface CellComment {
  id: string;
  /** Ответ на КОНКРЕТНУЮ запись треда (`parent_id` канона) — не на её корень.
   *  Ключа нет — запись корневая.
   *
   *  ССЫЛКА ИМЕННО НА АДРЕСАТА, хотя показываются ответы одним уровнем
   *  отступа (см. `threadOrder`). Пока сюда клался корень, «ответить» на
   *  третьей реплике подряд теряло, КОМУ отвечают: в ленте оставалось четыре
   *  одинаково вложенных записи без единого признака, какая какой возражает.
   *  Хранение адресата и ПОКАЗ вложенности — разные вопросы, и решать их
   *  одним полем значило отвечать на второй ценой первого. */
  parentId?: string;
  author: string;
  /** Когда написано, словами: «сегодня, 11:42». Строкой, а не датой: формат
   *  относительного времени решает источник, у которого есть часовой пояс
   *  пользователя. */
  at: string;
  /** Версия КП, к которой относится запись: «v3». Ключа нет — версий у КП
   *  нет вовсе. */
  version?: string;
  text: string;
  /** Лично мной не просмотрено. Ключа нет — просмотрено. */
  unread?: true;
}

/** Все треды снимка: ключ — адрес ячейки. Плоская карта, а не дерево по
 *  подрядчикам: читатель всегда знает ОБА конца адреса, и промежуточный
 *  уровень был бы лишним шагом на каждом обращении. */
export type CommentMap = Readonly<Record<string, CellComment[]>>;

/** Адрес треда. Тот же порядок и тот же разделитель, что у `data-cell`
 *  ячейки и у ключей подсветки перехода: три места, где пара «подрядчик ×
 *  позиция» становится строкой, обязаны собирать её одинаково. */
export const commentKey = (contractorId: string, positionId: string): string =>
  `${contractorId}:${positionId}`;

/** Записи треда в порядке показа: корневая, следом ВСЯ её ветка сверху вниз.
 *  Список плоский — вложенность на экране ровно одна (канон), — но обход
 *  честно рекурсивный: ответ на ответ существует (см. `parentId`), и порядок
 *  «сразу за своим адресатом» единственный, при котором переписку можно
 *  читать подряд.
 *
 *  СИРОТЫ НЕ ТЕРЯЮТСЯ: запись, чей `parentId` указывает в никуда (адресата
 *  удалили, ответ пришёл раньше родителя), дописывается в хвост. Молча
 *  выпасть из ленты она права не имеет — это чужие слова. */
export function threadOrder(comments: readonly CellComment[]): CellComment[] {
  const kids = new Map<string, CellComment[]>();
  for (const c of comments) {
    if (!c.parentId) continue;
    const list = kids.get(c.parentId);
    if (list) list.push(c); else kids.set(c.parentId, [c]);
  }
  const out: CellComment[] = [];
  const walk = (c: CellComment) => {
    out.push(c);
    for (const kid of kids.get(c.id) ?? []) walk(kid);
  };
  for (const root of comments) if (!root.parentId) walk(root);
  const seen = new Set(out.map((c) => c.id));
  return [...out, ...comments.filter((c) => !seen.has(c.id))];
}

/** Кому адресована запись — имя автора её родителя. `undefined` у корневой и
 *  у сироты. Считается по треду, а не хранится при записи: имя автора живёт
 *  в одном месте, и вторая копия разъехалась бы с ним при переименовании. */
export function addresseeOf(
  comment: CellComment, comments: readonly CellComment[],
): string | undefined {
  if (!comment.parentId) return undefined;
  return comments.find((c) => c.id === comment.parentId)?.author;
}

/** Есть ли в треде непросмотренное — им и различаются два глифа маркера
 *  (`chat-round-unread-bold` против `chat-round-bold`). Счётчика у маркера
 *  нет намеренно (решение владельца 25.08.2026): состояние несёт сам глиф. */
export const hasUnread = (comments: readonly CellComment[]): boolean =>
  comments.some((c) => c.unread === true);

/** Инициалы автора для аватара — одна-две буквы. Считаются, а не приходят
 *  полем: два источника одного и того же разъехались бы на первом же
 *  переименовании, а буквы из имени выводятся однозначно. */
export function initialsOf(author: string): string {
  const words = author.trim().split(/\s+/).filter(Boolean);
  if (!words.length) return '?';
  return words.slice(0, 2).map((w) => w[0]!.toUpperCase()).join('');
}

/** Тон аватара автора — ДЕТЕРМИНИРОВАННЫЙ от имени: один человек всегда
 *  одного цвета, в любом треде и в любой сессии. Случайный цвет читался бы
 *  как признак («почему он оранжевый?»), а цвет от имени — просто способ
 *  различать соседние записи глазом.
 *
 *  Три тона, а не пять: тревожные (warning-как-опасность, danger) в списке
 *  людей означали бы оценку человека. */
const AVATAR_TONES = ['info', 'success', 'warning'] as const;
export type CommentAvatarTone = typeof AVATAR_TONES[number];

export const avatarTone = (author: string): CommentAvatarTone => {
  let h = 7;
  for (const ch of author) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return AVATAR_TONES[h % AVATAR_TONES.length];
};
