/** Сравнение коммерческих предложений по одному тендеру: позиции сметы слева,
 *  подрядчики колонками справа. ЭТОТ ФАЙЛ — КОНТРАКТ ДАННЫХ: формы ответа и
 *  прямые обращения к ним, НИ ОДНОЙ СТРОКИ ДАННЫХ И НИ ОДНОЙ ФОРМУЛЫ.
 *
 *  Слайс разложен по сегментам, и граница между ними — вопрос «что это»:
 *  - `contract.ts` — формы ответа (здесь);
 *  - `thresholds.ts` — пороги аналитики, настройки тендера;
 *  - `calc.ts` — счёт: итоги, ранжир, производные числа строки;
 *  - `filters.ts` — предикаты среза;
 *  - `view.ts` — оси состояния экрана;
 *  - `lib/format.ts` — деньги и числа словами;
 *  - `api/` — откуда данные берутся.
 *
 *  Смета и КП приходят снаружи (сегодня из `api/comparison.mock.ts`, завтра из
 *  ответа сервера) и передаются в функции явным аргументом. Значений по
 *  умолчанию у аргументов НЕТ намеренно: `rankBids()` без аргументов
 *  подставляла бы демо-подрядчиков, и на живом экране это заметили бы по чужим
 *  именам в колонках, а в `spread()` — вообще никак: проценты правдоподобны
 *  любые.
 *
 *  Живёт в entities, а не в слайсе страницы, по той же причине, что и реестр:
 *  цифры на карточке подрядчика (сумма, место) и цифры в теле таблицы (цена
 *  позиции, итог группы, разброс) считаются ИЗ ОДНИХ И ТЕХ ЖЕ строк.
 *  Разъехавшись, они дали бы экран, который спорит сам с собой: карточка
 *  говорит одно, сумма по колонке — другое.
 *
 *  ЦЕНА ХРАНИТСЯ ЗА ЕДИНИЦУ, а не суммой по позиции. Подрядчик подаёт КП
 *  расценками, объём берётся из сметы тендера и у всех одинаков — храня сумму,
 *  мы дали бы возможность записать её несогласованной с объёмом, а разброс по
 *  строке считался бы уже по «своим» объёмам у каждого. Сумма выводится.
 *
 *  ОТСУТСТВИЕ КЛЮЧА — ЭТО «ПОЗИЦИЯ НЕ ЗАКРЫТА», а не ноль. Ноль означал бы
 *  «готовы сделать бесплатно» и попал бы и в сумму, и в разброс.
 *
 *  ПОМЕТКИ ЯЧЕЕК ПРИХОДЯТ ГОТОВЫМИ В ДАННЫХ — макет их рисует, не вычисляет
 *  (§5 аудита): аномальная цена с причиной, потенциал за единицу, отказ.
 *  Производные от порогов состояния считаются в `calc.ts`, в одном проходе
 *  `analyzeComparison()`, чтобы таблица, фильтры, счётчики и попап читали
 *  одни и те же числа. */

import type { Tone } from '@/shared/ui/Badge';
import type { IconName } from '@/shared/ui/Icon';

/* ═══════════════════ РАУНДЫ ТОРГОВ ═══════════════════
   Исходный сбор КП — раунд 1, каждый запущенный круг увеличивает номер
   (`demo/tender-round.md`, US-4). У раунда один актуальный анализ; сохранённый
   разбор прошлого раунда — снимок завершённого круга и не устаревает
   (05-ai-analysis.md §8). */

export type RoundStatus = 'current' | 'closed';

export interface ComparisonRound {
  id: string;
  /** Сквозной номер по тендеру, с 1. */
  number: number;
  status: RoundStatus;
  /** Приглашённые подрядчики раунда (id) — и подавшие, и ещё молчащие:
   *  состав раунда определяет, кого ждать с КП. */
  invited: string[];
}

export interface ComparePosition {
  id: string;
  title: string;
  qty: number;
  unit: string;
  /** Путь позиции в ФКП сверху вниз, БЕЗ самого названия: `['Отделка',
   *  'Полы']`. Нужен плоским видам — отсортированный список смешивает кровлю
   *  с инженерией, и без пути специалист не может сказать, в каком разделе
   *  торговаться (`rows.md` §2, `position.md` §1).
   *
   *  ПОЛЕ, А НЕ ВЫВОД ИЗ `PositionGroup`: группа даёт ровно один уровень
   *  («секция»), а ФКП вложена глубже — «Отделка › Полы › Наливные
   *  покрытия». Вывести второй уровень из первого нечем, и попытка сделать
   *  это на клиенте дала бы путь, который врёт ровно там, где он и нужен.
   *  Ключа нет — путь совпадает с секцией, и крошки показывают её одну. */
  sectionPath?: string[];
  /** Ручная пометка закупщика. Правило «топ по весу» добавляет ключевые
   *  поверх ручных (`analyzeComparison`): одно другому не мешает. */
  key?: boolean;
  /** Объём до корректировки сметы: дифф против опубликованного показывают
   *  ОБА значения (`920 → 840`), молчаливая подмена врала бы истории. */
  qtyOrig?: number;
  /** Строка снята из сметы после публикации. Остаются в DOM и в счётчиках —
   *  это часть истории сметы, а не мусор. */
  removed?: boolean;
}

/* ═══════════════════ КОРРЕКТИРОВКА ОБЪЁМА ═══════════════════
   Поставщик назвал цену за ДРУГОЙ объём, чем стоит в смете, и до решения
   тендерщика этой паре цен верить нельзя: они посчитаны по разным количествам.
   Канон — `corrections.md`, знак ⚠ и его три оси — разбор 23.08.2026
   («2026-08-23-correction-warning-sign.md»). */

/** Состояние решения по корректировке (`metrics.md` §3). Три, а не флаг
 *  «есть/нет»: после решения корректировка НИКУДА НЕ ДЕВАЕТСЯ — она уходит в
 *  историю ячейки, — но знак ⚠ гаснет, и различать «ещё не решено» от «решено»
 *  обязан сам ответ, а не отсутствие поля. Знак существует РОВНО в
 *  `pending`. */
export type CorrectionStatus = 'pending' | 'accepted' | 'declined';

export interface QtyCorrection {
  /** Объём, названный поставщиком вместо сметного. */
  qty: number;
  status: CorrectionStatus;
  /** Обоснование поставщика — раскрывается по наведению на знак
   *  (`corrections.md` §3). Ключа нет — обоснования не приложили. */
  note?: string;
  /** Комментарий ТЕНДЕРЩИКА к принятому решению. Отдельным полем от `note`,
   *  а не поверх него: это два текста двух сторон, и затирание обоснования
   *  поставщика решением стёрло бы половину истории ячейки. Обязателен при
   *  отклонении (`correction.md` §3) — проверяет форма панели. */
  decisionNote?: string;
}

/** Пометка ячейки «позиция × подрядчик». Всё — вход, ни одно поле не
 *  выводится из цен: аномалия — вердикт внешнего анализа, потенциал —
 *  торговая оценка, отказ — решение подрядчика (§5 аудита). */
export interface CellMark {
  /** Причина аномалии — обязательна при ней же: строку невозможно объяснить
   *  подрядчику без причины, поэтому попап показывает её первым блоком.
   *  У ячейки, помеченной ТОЛЬКО формулой (без внешнего вердикта), причины
   *  нет — попап даёт стандартную фразу вместо неё. */
  anomaly?: string;
  /** Заявленный запас торга, ₽ ЗА ЕДИНИЦУ — как и цена: сумма по строке
   *  выводится умножением на общий объём. */
  potential?: number;
  /** Отказ от объёма. Противоположен пробелу данных: отказ — решение,
   *  отсутствие цены — дыра в КП; красить решение в тревогу — врать о нём. */
  declined?: boolean;
  /** Комментарий разбора к этой ячейке («почему важно / что делать»).
   *  Приходить может ТОЛЬКО после запуска анализа (Р4): до него попап
   *  показывает одни числа, словарь пометок живёт в легенде. У «нет цены»
   *  и «Отказа» комментария не бывает вовсе (05 §4.3.4). */
  note?: string;
  /** Поставщик назвал цену за ДРУГОЙ объём. Ключа нет — объём общий, как в
   *  смете. Взаимоисключается с `declined` по природе данных: отказ
   *  действует сразу и решения не требует. */
  correction?: QtyCorrection;
  /** СОСТАВ СТАВКИ: материалы и работы по отдельности, ₽ за единицу
   *  (`cell.md` §3 — «обе ставки и их сумма»). Приходит полем, а не делится
   *  на клиенте: пропорция у каждой работы своя и известна только
   *  поставщику.
   *
   *  СУММА ЭТИХ ДВУХ ОБЯЗАНА СХОДИТЬСЯ С `prices[positionId]`, и карточка
   *  ячейки показывает обе строки рядом именно поэтому: расхождение видно
   *  глазом. Ключа нет — состав не раскрыт, и строки в карточке не будет
   *  вовсе (а не «0 + 0»). */
  rates?: { materials: number; works: number };
  /** ЖДЁМ ОТВЕТ ПОСТАВЩИКА по этой позиции — четвёртое состояние значения
   *  (`cell.md` §1.2, `pricing.md` §4), а не разновидность пробела.
   *
   *  Пробел и ожидание требуют РАЗНЫХ действий: по пробелу запрашивают цену,
   *  по ожиданию ждут или напоминают. Слипшись в один прочерк, они искажают
   *  и картину полноты КП, и проценты заполнения — «у него дыра в смете» и
   *  «он ещё пишет» это два разных разговора с подрядчиком.
   *
   *  Приходит ПОЛЕМ ПОДАЧИ: знает об этом только источник (запрос ушёл,
   *  ответа нет), из цен вывести нельзя. Живёт при ОТСУТСТВИИ цены — цена
   *  есть, значит ответ уже получен, и флаг игнорируется. */
  waiting?: true;
}

/** Раздел сметы («секция»). Плоский список из десятков позиций читается как
 *  простыня: секции дают итог промежуточный («материалы у всех примерно
 *  одинаковы, а расходятся на работах») и дают что свернуть, когда строки
 *  уже прочитаны. */
export interface PositionGroup {
  id: string;
  title: string;
  positions: ComparePosition[];
}

/* ═══════════════════ УСЛОВИЯ ПОСТАВЩИКА ═══════════════════
   Ответы формы КП вне цен (аванс, срок, гарантия…) — матрица внизу таблицы:
   строки-вопросы, колонки-подрядчики. Состав вопросов знает ТОЛЬКО источник
   данных (форма ФКП): экран рисует матрицу по факту, объединяя строки по
   `label`, поэтому подпись вопроса — стабильный ключ, а не украшение. */

/** Как ячейка матрицы отвечает сама за себя:
 *  - `bool` — да/нет, рисуется иконкой тона (значение остаётся текстом);
 *  - `value` — число или срок текстом;
 *  - `note` — развёрнутый текст, наружу торчит кнопка с попапом. */
export type TermKind = 'bool' | 'value' | 'note';

export interface SupplierTerm {
  id: string;
  /** Вопрос формы — он же ключ строки матрицы у ВСЕХ подрядчиков. */
  label: string;
  /** Ответ словами формы: «40 %», «4 месяца», «да». */
  value: string;
  kind: TermKind;
}

/** Состояние КП. Отвечает на вопрос «можно ли по этому предложению принимать
 *  решение», а не «сколько строк заполнено» — заполненность стоит на карточке
 *  отдельно. Пример, ради которого статус вообще нужен полем: КП заполнено
 *  целиком, но к нему есть вопросы, и подписывать его сейчас нельзя. Из
 *  процентов этого не видно.
 *
 *  Подписи — ОДНО слово, сказанное о КП: «(КП) получено / уточняется /
 *  частично». Длинные расшифровки («Заполнено частично») в капсуле шапки
 *  колонки не помещались и читались как предложение; смысл целиком остаётся
 *  доступным по наведению на карточку (процент заполнения рядом).
 *
 *  Цвет — ОБЩИЙ мягкий тон: тот же вид капсулы, что у статусов реестра
 *  («Открыт», «Закрыт», «Отменён»). Плотную заливку сняли после трёх проб за
 *  день (ступень -ink — слишком глухо; полтона к белому — серо; сам цвет тона
 *  с белым текстом — «не наши» цвета; 23.08.2026) — разбор в Части XII
 *  DESIGN-NOTES. */
export type BidStatusId = 'complete' | 'revision' | 'partial';

export interface BidStatusView {
  label: string;
  tone: Tone;
  icon: IconName;
}

export const BID_STATUS: Record<BidStatusId, BidStatusView> = {
  complete: { label: 'Получено', tone: 'success', icon: 'inbox' },
  revision: { label: 'Уточняется', tone: 'warning', icon: 'questionCircle' },
  partial: { label: 'Частично', tone: 'info', icon: 'checklistMin' },
};

/** Статус по id — ФУНКЦИЕЙ, а не обращением к таблице. Граница доверия: id
 *  приходит из ответа сервера, где словарь статусов живёт своей жизнью и
 *  пополняется без нас. Незнакомое значение обязано дать нейтральную капсулу
 *  с самим id — видно, что статус новый, — а не уронить экран на
 *  `undefined.label`. */
export const bidStatus = (id: string): BidStatusView =>
  BID_STATUS[id as BidStatusId] ?? { label: id, tone: 'neutral', icon: 'flag' };

/* ═══════════════════ СТАДИЯ УЧАСТНИКА ═══════════════════
   Состав участников — часть картины торга: «против кого играем и кто молчит»
   видно из таблицы, а не из списка контрагентов (`contractor.md` §4).
   Стадия ОТВЕЧАЕТ НЕ ЗА КП, А ЗА УЧАСТНИКА, и потому отдельна от
   `BidStatusId`: статус говорит «можно ли принимать решение по этому КП»,
   стадия — «есть ли вообще КП, которое можно смотреть». */

export type BidStage =
  /** Подал в текущем раунде — обычная колонка с числами. */
  | 'submitted'
  /** Приглашён, КП ещё нет: колонка со стадией и «ждём предложение». */
  | 'invited'
  /** Черновик у себя, не подан — числа нам не видны. */
  | 'draft'
  /** Подал в ПРОШЛОМ раунде и не переподал: числа прошлой подачи с пометкой. */
  | 'stale'
  /** Закрытый доступ: данные показываются справочно, из расчёта исключены. */
  | 'locked';

/** Стадия участника или значение по умолчанию. Функцией, а не
 *  `contractor.stage ?? 'submitted'` по месту: ключа нет у ВСЕХ старых
 *  данных, и «подал» обязано быть одним решением, а не десятью одинаковыми. */
export const bidStage = (contractor: Contractor): BidStage =>
  contractor.stage ?? 'submitted';

/** ПОДПИСЬ СОСТОЯНИЯ КОЛОНКИ ОДНОЙ СТРОКОЙ: стадия старше статуса КП.
 *
 *  Стадия отвечает на вопрос «есть ли вообще предложение и можно ли его
 *  считать» (приглашён, черновик, доступ закрыт, не переподал), статус — на
 *  вопрос «в каком состоянии поданное КП» (получено, уточняется, частично).
 *  Первый вопрос старше: у приглашённого статус КП существует формально, но
 *  говорить о нём нечего.
 *
 *  ЖИВЁТ В КОНТРАКТЕ, А НЕ В КАРТОЧКЕ, потому что это СЛОВАРЬ ДОМЕНА, а не
 *  вёрстка: те же слова читают подвал карточки, её же `title`, досье и
 *  выгрузка. Собранная по месту цепочка тернарников разъезжается с соседями
 *  на первой правке словаря — и разъехалась бы молча. */
export const stageLabel = (contractor: Contractor): string => {
  const stage = bidStage(contractor);
  return stage === 'stale' ? 'не переподал'
    : stage === 'invited' ? 'приглашён'
      : stage === 'draft' ? 'черновик'
        : stage === 'locked' ? 'доступ закрыт'
          : bidStatus(contractor.status).label;
};

/** НУЖНА ЛИ КАПСУЛА СОСТОЯНИЯ РЯДОМ С ПРОЦЕНТОМ ЗАПОЛНЕНИЯ (§7 правок
 *  владельца 25.08.2026: «тут присутствует дублирование логики — получено,
 *  100 % заполнено»).
 *
 *  «Получено» и «100 % заполнено» — ОДИН факт, сказанный дважды: статус
 *  `complete` и есть «расценки стоят у всей сметы», а `partial` — «стоят не у
 *  всей», и число процентов называет то же самое ТОЧНЕЕ. Капсула остаётся
 *  там, где полнота молчит: `revision` (уточняется — это процесс, а не
 *  заполненность) и любая стадия, кроме поданной, — у них собственного числа
 *  нет вовсе. */
export const needsStageBadge = (contractor: Contractor): boolean =>
  bidStage(contractor) !== 'submitted' || contractor.status === 'revision';

/** Участвует ли колонка в РАСЧЁТЕ — ранжире, минимуме строки, разбросе,
 *  аномалиях, итогах. Единственная дверь: разъедься читатели, приглашённый
 *  без цен обвалил бы медиану строки нулём, а колонка с закрытым доступом
 *  претендовала бы на первое место (`contractor.md` §4).
 *
 *  Считаются `submitted` и `stale`: «не переподал» — это реальные цены
 *  реального КП, просто прошлого круга, и прятать их из сравнения значило бы
 *  показывать торг без одного из участников. `locked` цены имеет, но в счёт
 *  не идёт — это и есть смысл замка. */
export const countsInAnalysis = (contractor: Contractor): boolean => {
  const stage = bidStage(contractor);
  return stage === 'submitted' || stage === 'stale';
};

/** Версия КП в шапке колонки (`contractor.md` §2). Переключение пересчитывает
 *  СНИМОК КОЛОНКИ — значит версия обязана нести собственные расценки, а не
 *  одну дату: без них «переключил» означало бы «сменил подпись». */
export interface BidVersion {
  id: string;
  /** Номер словами формы: «v3». */
  label: string;
  /** Когда подана, ДД.ММ.ГГГГ. */
  date: string;
  /** Расценки этой версии. Ключа нет — версия зарегистрирована, но её файл
   *  не разобран: в меню она видна с прочерком вместо итога и не выбирается. */
  prices?: Record<string, number>;
}

export interface Contractor {
  id: string;
  name: string;
  status: BidStatusId;
  /** Заполненность КП в процентах — доля сметы ПО СТОИМОСТИ, закрытая
   *  расценками. Поле, а не «сколько строк из тринадцати»: смета неоднородна,
   *  и незакрытая плёнка за 80 тысяч и незакрытая гидроизоляция за миллион —
   *  это одна строка и там, и там, но совсем разная дыра в предложении.
   *  Долю по строкам считает `filled` в Bid и показывает только скринридеру. */
  fill: number;
  inn: string;
  contact: string;
  /** Когда КП поступило, ДД.ММ.ГГГГ — как и прочие даты в домене. */
  submitted: string;
  /** Цена за единицу по id позиции. Ключа нет — позиция в КП не закрыта. */
  prices: Record<string, number>;
  /** Пометки анализа по id позиции. Ключа нет — ячейка чистая: ни аномалии,
   *  ни потенциала, ни отказа (отказ живёт здесь, а не отсутствием цены). */
  marks?: Record<string, CellMark>;
  /** Номер раунда, в который подано ЭТО КП. Ключа нет — КП первого раунда:
   *  поле появилось вместе с раундами, старые данные молча считаются первым
   *  кругом. «Ещё не подал» в текущем раунде = номер меньше текущего. */
  submittedInRound?: number;
  /** Условия КП («аванс 30 %») — их анализ обязан назвать РАНЬШЕ слова
   *  «аномалия» (05-ai-analysis.md §4.3.3): условия могут объяснять цену. */
  conditions?: string[];
  /** Расценки этого же подрядчика из предыдущего раунда — база секции
   *  «Изменения поставщика» (05 §4.1): сравнивают его же прошлое КП,
   *  а не чужие предложения. */
  prevPrices?: Record<string, number>;
  /** Условия его же прошлого КП. Отдельным полем, потому что условия меняются
   *  БЕЗ цен: круг, где подрядчик переписал аванс и не тронул расценки, без
   *  этого снимка читается как «не менялся» (граничный случай 05 §4.1).
   *  Ключа нет — прошлых условий не знаем, и строки об изменении не будет. */
  prevConditions?: string[];
  /** Ответы формы КП вне цен (п.9): аванс, срок, гарантия… Ключа нет — форма
   *  ещё не собрана, и матрица условий у тендера не рисуется вовсе. */
  terms?: SupplierTerm[];
  /** Стадия участника. Ключа нет — подал (см. `bidStage`): поле появилось
   *  вместе с приглашёнными, и старые данные молча остаются поданными. */
  stage?: BidStage;
  /** Поданные версии КП, СТАРШАЯ ПЕРВОЙ. Ключа нет — версия одна, и селект в
   *  шапке не рисуется: выбирать не из чего (`contractor.md` §2). */
  versions?: BidVersion[];
  /** Какая версия показана СЕЙЧАС. Ключа нет — старшая. Поле ответа, а не
   *  состояние экрана: выбор версии фиксируется в выгрузке и виден коллеге
   *  по ссылке, значит живёт при данных, а не при просмотре. */
  versionId?: string;
  /** Файл-источник КП: имя для строки «Источник» карточки ячейки (`cell.md`
   *  §3). Ключа нет — файл не приложен, и строка не рисуется вовсе. */
  sourceFile?: string;
}

/** Ответ на «дай сравнение по тендеру» — ровно то, чем живёт экран, и ничего
 *  больше. Смета отдельно от КП, а не расценки внутри позиции: подрядчик
 *  вправе позицию не закрыть, и место для этого «нет» есть только в КП. */
export interface Comparison {
  groups: PositionGroup[];
  contractors: Contractor[];
  /** Реестр раундов тендера — для переключателя сохранённых анализов.
   *  Ключа нет — раунды ещё не заводились, панель показывает один круг. */
  rounds?: ComparisonRound[];
  /** Номер раунда, состоянию которого соответствует ЭТОТ снимок КП. Ключа нет
   *  — данные первого раунда. Без него реестр раундов и расценки ответа
   *  разъехались бы: реестр знает про второй круг, а цены в ответе — прошлые. */
  roundNumber?: number;
  /** Ревизия данных сравнения — растёт на КАЖДОЙ подаче КП. Поле ОТВЕТА, а не
   *  вычисление на клиенте: сравнивать нечего, пока не с чем сравнить, и
   *  единственный, кто знает о подаче, — сервер. По нему панель разбора
   *  понимает, что сохранённый результат устарел (05 §8.2). */
  revision?: string;
  /** Причина последнего изменения данных — текст плашки устаревания
   *  («поставщик прислал новое КП»). Тоже поле ответа: событие произошло на
   *  сервере, и назвать его может только он. */
  revisionNote?: string;
}

/** Раунд, к которому относится снимок: явное поле, иначе текущий статус
 *  реестра, иначе первый круг. Одна функция, чтобы трое читавших это место
 *  не разошлись. */
export const snapshotRound = (comparison: Comparison): number =>
  comparison.roundNumber
  ?? comparison.rounds?.find((r) => r.status === 'current')?.number
  ?? 1;

/** Есть ли предыдущий раунд у снимка — секции «Изменения поставщика» и
 *  «Общая картина» появляются именно потому, что появилось с чем сравнивать
 *  (05 §4); их отсутствие в первом раунде — норма, а не пустая секция. */
export const hasPreviousRound = (comparison: Comparison): boolean => {
  const n = snapshotRound(comparison);
  return !!comparison.rounds?.some((r) => r.number === n - 1);
};

/** Плоский список позиций — для расчётов, которым разделы безразличны (итог по
 *  КП, сколько позиций закрыто). ВЫВОДИТСЯ из разделов, а не приходит вторым
 *  полем ответа: два перечня одних и тех же позиций разъехались бы на первой
 *  же правке — хоть у нас, хоть на сервере. */
export const flatten = (groups: PositionGroup[]): ComparePosition[] =>
  groups.flatMap((g) => g.positions);

/** Пометки ячейки или пусто. Функцией, а не `contractor.marks?.[id]` по месту:
 *  единственное место знает, что пометки могут не прийти вовсе. */
export const cellMark = (contractor: Contractor, positionId: string): CellMark =>
  contractor.marks?.[positionId] ?? {};

export const hasAnomaly = (mark: CellMark): boolean => typeof mark.anomaly === 'string';

/** Корректировка, ТРЕБУЮЩАЯ РЕШЕНИЯ, — или ничего. Единственная дверь к
 *  знаку ⚠ во всех трёх его осях (ячейка, шапка колонки, строка): счёт в
 *  шапке, счёт в строке и гашение после решения стоят на одном и том же
 *  условии, и разъехаться им можно только если каждый читатель проверяет
 *  статус сам. Принял или отклонил — здесь `undefined`, и знак исчезает
 *  везде разом (разбор 23.08.2026, §1 и §6). */
export const pendingCorrection = (mark: CellMark): QtyCorrection | undefined =>
  (mark.correction?.status === 'pending' ? mark.correction : undefined);

/** Ждём ли ответ поставщика по этой ячейке. Дверь одна — как у ⚠: состояние
 *  читают ячейка, сводка и счётчик полноты, и разъехаться им нельзя.
 *  Цена ЕСТЬ — значит ответ получен, и флаг подачи уже неактуален: проверка
 *  стоит здесь, а не у трёх читателей. */
export const isWaiting = (contractor: Contractor, positionId: string): boolean =>
  contractor.prices[positionId] === undefined && cellMark(contractor, positionId).waiting === true;

/** Действующая версия КП: выбранная или старшая. `undefined` — версий нет
 *  вовсе, селект в шапке не рисуется. */
export const currentVersion = (contractor: Contractor): BidVersion | undefined => {
  const list = contractor.versions;
  if (!list?.length) return undefined;
  return list.find((v) => v.id === contractor.versionId) ?? list[0];
};

/** Показана ли НЕ последняя версия — шапка обязана сказать это словом
 *  «неактуальная» и дать возврат одним действием (`contractor.md` §2). */
export const isStaleVersion = (contractor: Contractor): boolean => {
  const list = contractor.versions;
  return !!list?.length && !!contractor.versionId && list[0].id !== contractor.versionId;
};

/** Снимок подрядчика под ВЫБРАННУЮ версию: расценки подменяются её
 *  расценками. Функция, а не правка объекта на месте: `analyzeComparison`
 *  считает по массиву подрядчиков, и подмена должна произойти ОДИН раз на
 *  входе в расчёт — иначе половина экрана считала бы по старшей версии, а
 *  половина по выбранной.
 *
 *  Версия без разобранного файла (`prices` нет) снимок НЕ меняет: выбрать её
 *  нельзя, но прийти сюда она может — данными правит сервер, не мы. */
export const withVersion = (contractor: Contractor): Contractor => {
  const version = currentVersion(contractor);
  if (!version?.prices || version.id === contractor.versions?.[0]?.id) return contractor;
  return { ...contractor, prices: version.prices };
};

/** Путь позиции для крошек: явный путь, иначе — одна секция, в которой она
 *  лежит. Одна функция, чтобы плоские виды и паспорт позиции не разошлись в
 *  том, что показывать при отсутствующем `sectionPath`. */
export const sectionPathOf = (
  position: ComparePosition, groups: PositionGroup[],
): string[] => {
  if (position.sectionPath) return position.sectionPath;
  const group = groups.find((g) => g.positions.some((p) => p.id === position.id));
  return group ? [group.title] : [];
};
